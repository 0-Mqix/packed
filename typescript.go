package packed

import (
	"bytes"
	"fmt"
	"reflect"
	"strings"
)

// The TypeScript generator: an ES module with the same byte layout as the Go
// output, for the browser and Node, in erasable syntax only,
// so Node and Vite run it as it is. An enum is a frozen array of its value
// names and the type of those names, read and written as the name; a
// struct an interface of its fields by camelName, and an object of the
// same name with write and read; a message set the union of its variants,
// { variant, message }, and an object whose encode takes one and whose
// decode returns one. Integers of 64 bits
// are BigInts, the others numbers; bytes (VariableBytes, a Slice of Uint8)
// a Uint8Array; bit runs are read and written through BigInt words. The
// reader and writer are the runtime's PackedReader and PackedWriter, which
// the module imports from runtime (packed's typescript/packed.ts). Reads
// are bounds-checked and throw RangeError; a message set's decode throws
// Error with Go's messages.

type typeScriptGenerator struct{}

// TypeScriptSource renders every registered enum, struct and message set as
// a TypeScript module that imports its reader and writer from runtime.
func TypeScriptSource(runtime string) []byte {
	generator := &typeScriptGenerator{}
	body := &sourceWriter{buffer: &bytes.Buffer{}}

	for _, name := range sortedKeys(enums) {
		generator.enum(body, enums[name])
		body.line("")
	}
	for _, name := range sortedKeys(messageSets) {
		generator.messageSet(body, messageSets[name])
		body.line("")
	}
	for _, name := range sortedKeys(structs) {
		generator.structure(body, structs[name])
		body.line("")
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "// Code generated by github.com/0-Mqix/packed; DO NOT EDIT.\n\n")
	fmt.Fprintf(result, "import { enumName, enumValue, PackedReader, PackedWriter } from %q;\n\n", runtime)
	result.Write(bytes.TrimRight(body.buffer.Bytes(), "\n"))
	return result.Bytes()
}

func (g *typeScriptGenerator) enum(w *sourceWriter, enum packedEnum) {
	names := make([]string, len(enum.values))
	for index, value := range enum.values {
		names[index] = fmt.Sprintf("%q", value)
	}
	w.line("export const %s = Object.freeze([%s] as const);", enum.name, strings.Join(names, ", "))
	w.line("export type %s = (typeof %s)[number];", enum.name, enum.name)
}

func (g *typeScriptGenerator) messageSet(w *sourceWriter, set packedMessageSet) {
	untagged := set.tagInBits && set.tagBits == 0
	variants := make([]string, len(set.variants))
	for index, variant := range set.variants {
		variants[index] = fmt.Sprintf("{ variant: %q; message: %s }", variant.structure.name, variant.structure.name)
	}
	w.line("export type %s = %s;", set.name, strings.Join(variants, " | "))
	w.line("")
	w.open("export const %s = Object.freeze({", set.name)

	w.line("// The message after prefix, bytes the caller fills (such as a routing byte).")
	w.open("encode(value: %s, prefix: ArrayLike<number> = []): Uint8Array {", set.name)
	w.line("const writer = new PackedWriter(prefix);")
	w.open("switch (value.variant) {")
	for _, variant := range set.variants {
		w.open("case %q:", variant.structure.name)
		if !set.tagInBits {
			w.line("writer.uint8(%d);", variant.typeByte)
		}
		w.line("%s.write(writer, value.message);", variant.structure.name)
		w.line("break;")
		w.indent--
	}
	w.open("default:")
	w.line("throw new Error(`packed: no %s variant ${(value as { variant: string }).variant}`);", set.name)
	w.indent--
	w.close("}")
	w.line("return writer.written();")
	w.close("},")
	w.line("")

	w.line("// The message that starts at index and runs to the end of bytes.")
	w.open("decode(bytes: Uint8Array, index = 0): %s {", set.name)
	tag := "${type}"
	if untagged {
		tag = "0"
		w.line("const reader = new PackedReader(bytes, index);")
	} else {
		w.line("if (bytes.length <= index) throw new Error('packed: empty %s message');", set.name)
		switch {
		case !set.tagInBits || set.tagBits == 8:
			w.line("const type = bytes[index];")
		case set.littleEndian:
			w.line("const type = bytes[index] & 0x%X;", bitMask(set.tagBits))
		default:
			w.line("const type = bytes[index] >>> %d;", 8-set.tagBits)
		}
		if set.tagInBits {
			w.line("const reader = new PackedReader(bytes, index);")
		} else {
			w.line("const reader = new PackedReader(bytes, index + 1);")
		}
	}
	w.line("let decoded: %s;", set.name)
	w.open("try {")
	if untagged {
		name := set.variants[0].structure.name
		w.line("decoded = { variant: %q, message: %s.read(reader) };", name, name)
	} else {
		w.open("switch (type) {")
		for _, variant := range set.variants {
			name := variant.structure.name
			w.open("case %d:", variant.typeByte)
			w.line("decoded = { variant: %q, message: %s.read(reader) };", name, name)
			w.line("break;")
			w.indent--
		}
		w.open("default:")
		w.line("throw new Error(`packed: unknown %s type ${type}`);", set.name)
		w.indent--
		w.close("}")
	}
	w.indent--
	w.open("} catch (error) {")
	w.line("if (error instanceof RangeError) throw new Error(`packed: truncated %s type %s`, { cause: error });", set.name, tag)
	w.line("throw error;")
	w.close("}")
	w.line("if (reader.index !== bytes.length) throw new Error(`packed: %s type %s has ${bytes.length - reader.index} trailing bytes`);", set.name, tag)
	w.line("return decoded;")
	w.close("},")
	w.close("});")
}

func (g *typeScriptGenerator) structure(w *sourceWriter, structure packedStruct) {
	if len(structure.properties) == 0 {
		w.line("export interface %s {}", structure.name)
		w.line("")
		w.open("export const %s = Object.freeze({", structure.name)
		w.line("write(writer: PackedWriter, value: %s): void {},", structure.name)
		w.line("")
		w.open("read(reader: PackedReader): %s {", structure.name)
		w.line("return {};")
		w.close("},")
		w.close("});")
		return
	}
	w.open("export interface %s {", structure.name)
	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			for _, field := range property.packed.(packedBitFieldGroup).fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				w.line("%s: %s;", camelName(field.packedProperty.name), g.bitFieldType(field))
			}
			continue
		}
		w.line("%s: %s;", camelName(property.name), g.typeOf(property.kind, property.packed, property.name))
	}
	w.close("}")
	w.line("")
	w.open("export const %s = Object.freeze({", structure.name)
	w.open("write(writer: PackedWriter, value: %s): void {", structure.name)
	for _, property := range structure.properties {
		g.writeProperty(w, property, "value", 0)
	}
	w.close("},")
	w.line("")
	w.open("read(reader: PackedReader): %s {", structure.name)
	w.line("const value = {} as %s;", structure.name)
	g.readStructure(w, structure, "value", 0)
	w.line("return value;")
	w.close("},")
	w.close("});")
}

// primitiveType is the TypeScript type of a primitive converter's value.
func primitiveType(primitive kotlinPrimitive) string {
	switch {
	case primitive.method == "boolean":
		return "boolean"
	case primitive.size == 8 && strings.Contains(primitive.method, "int"):
		return "bigint"
	}
	return "number"
}

// typeOf is the TypeScript type of a value of kind.
func (g *typeScriptGenerator) typeOf(kind kind, packed any, location string) string {
	switch kind {
	case kindStruct:
		return packed.(packedStruct).name
	case kindEnum:
		return packed.(packedEnum).name
	case kindVariableString:
		if packed.(packedVariableString).Bytes {
			return "Uint8Array"
		}
		return "string"
	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, location, "TypeScript"); ok {
			return primitiveType(primitive)
		}
		return "string"
	case kindArray:
		array := packed.(packedArray)
		return g.typeOf(array.ElementKind, array.Element, location) + "[]"
	case kindSlice:
		slice := packed.(packedSlice)
		if byteElements(slice.ElementKind, slice.Element) {
			return "Uint8Array"
		}
		return g.typeOf(slice.ElementKind, slice.Element, location) + "[]"
	}
	panic(fmt.Sprintf("%s uses a custom Go type, which has no TypeScript mapping", location))
}

// bitFieldType is the TypeScript type of a bit field's value.
func (g *typeScriptGenerator) bitFieldType(field packedBitField) string {
	switch field.bitFieldKind {
	case bitFieldKindBoolean:
		return "boolean"
	case bitFieldKindEnum:
		return field.enum.name
	case bitFieldKindInteger:
		if kotlinIntegers[field.reflection.Kind()].size == 8 {
			return "bigint"
		}
		return "number"
	}
	panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no TypeScript mapping", field.packedProperty.name))
}

// byteElements reports whether a slice holds plain bytes: a Uint8Array in
// TypeScript, as VariableBytes is, in the same layout.
func byteElements(kind kind, element any) bool {
	if kind != kindConverter {
		return false
	}
	reflection := reflect.TypeOf(element)
	if reflection.Kind() == reflect.Ptr {
		reflection = reflection.Elem()
	}
	return reflection == reflect.TypeFor[Uint8Converter]()
}

// typeScriptVariable names the reader's and writer's method of a variable
// string or byte run.
func typeScriptVariable(packed any) string {
	if packed.(packedVariableString).Bytes {
		return "bytesOf"
	}
	return "text"
}

// endianArgument is a multi-byte read's or write's endianness argument.
func endianArgument(size int, littleEndian bool) string {
	if size == 1 {
		return ""
	}
	return fmt.Sprintf("%t", littleEndian)
}

func typeScriptCall(receiver, method string, arguments ...string) string {
	kept := []string{}
	for _, argument := range arguments {
		if argument != "" {
			kept = append(kept, argument)
		}
	}
	return fmt.Sprintf("%s.%s(%s)", receiver, method, strings.Join(kept, ", "))
}

func (g *typeScriptGenerator) writeProperty(w *sourceWriter, property packedProperty, target string, depth int) {
	if property.kind == kindBitFieldGroup {
		g.writeBits(w, property.packed.(packedBitFieldGroup), property.littleEndian, target)
		return
	}
	g.writeValue(w, property.kind, property.packed, target+"."+camelName(property.name), property.littleEndian, depth)
}

func (g *typeScriptGenerator) writeValue(w *sourceWriter, kind kind, packed any, value string, littleEndian bool, depth int) {
	switch kind {
	case kindStruct:
		for _, child := range packed.(packedStruct).properties {
			g.writeProperty(w, child, value, depth)
		}

	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, value, "TypeScript"); ok {
			w.line("%s;", typeScriptCall("writer", primitive.method, value, endianArgument(primitive.size, littleEndian)))
			return
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		w.line("writer.fixedText(%s, %d);", value, length)

	case kindEnum:
		enum := packed.(packedEnum)
		primitive := kotlinIntegers[enum.reflection.Kind()]
		w.line("%s;", typeScriptCall("writer", primitive.method, fmt.Sprintf("enumValue(%s, %s)", enum.name, value), endianArgument(primitive.size, littleEndian)))

	case kindVariableString:
		variable := packed.(packedVariableString)
		w.line("writer.%s(%s, %d, %t);", typeScriptVariable(packed), value, variable.Length.size, littleEndian)

	case kindArray:
		array := packed.(packedArray)
		w.line("if (%s.length !== %d) throw new RangeError(`%s must hold %d items, not ${%s.length}`);", value, array.Length, value, array.Length, value)
		item := itemName(depth)
		w.open("for (const %s of %s) {", item, value)
		g.writeValue(w, array.ElementKind, array.Element, item, littleEndian, depth+1)
		w.close("}")

	case kindSlice:
		slice := packed.(packedSlice)
		if slice.maximum > 0 {
			w.line("if (%s.length > %d) throw new RangeError(`%s holds more than its maximum of %d items`);", value, slice.maximum, value, slice.maximum)
		}
		if byteElements(slice.ElementKind, slice.Element) {
			w.line("writer.bytesOf(%s, %d, %t);", value, slice.Length.size, littleEndian)
			return
		}
		w.line("writer.length(%s.length, %d, %t);", value, slice.Length.size, littleEndian)
		item := itemName(depth)
		w.open("for (const %s of %s) {", item, value)
		g.writeValue(w, slice.ElementKind, slice.Element, item, littleEndian, depth+1)
		w.close("}")

	default:
		panic(fmt.Sprintf("%s uses a custom Go type, which has no TypeScript mapping", value))
	}
}

// bigMask is a mask of bits as a BigInt literal.
func bigMask(bits int) string {
	if bits >= 64 {
		return "0xFFFFFFFFFFFFFFFFn"
	}
	return fmt.Sprintf("0x%Xn", bitMask(bits))
}

func bigShiftLeft(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s << %dn)", expression, shift)
}

func bigShiftRight(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s >> %dn)", expression, shift)
}

// wordVariable names a bit run's word, by its group and the path of the
// struct it is in.
func wordVariable(target string, word int) string {
	path := strings.Map(func(letter rune) rune {
		if letter == '.' || letter == '[' || letter == ']' {
			return -1
		}
		return letter
	}, strings.TrimPrefix(target, "value"))
	if path == "" {
		return fmt.Sprintf("bits%d", word)
	}
	return fmt.Sprintf("%sBits%d", strings.ToLower(path[:1])+path[1:], word)
}

func (g *typeScriptGenerator) writeBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, target string) {
	placements := group.placements(littleEndian)
	for word := 0; word < wordCount(group.size); word++ {
		variable := wordVariable(target, group.groupIndex+word)
		w.line("let %s = 0n;", variable)
		for _, placement := range placements {
			field := placement.field
			value := target + "." + camelName(field.packedProperty.name)
			var source string
			switch field.bitFieldKind {
			case bitFieldKindTag:
				source = fmt.Sprintf("%dn", field.tagValue)
			case bitFieldKindBoolean:
				source = fmt.Sprintf("(%s ? 1n : 0n)", value)
			case bitFieldKindEnum:
				source = fmt.Sprintf("(BigInt(enumValue(%s, %s)) & %s)", field.enum.name, value, bigMask(field.bitSize))
			case bitFieldKindInteger:
				source = fmt.Sprintf("(BigInt(%s) & %s)", value, bigMask(field.bitSize))
			default:
				panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no TypeScript mapping", field.packedProperty.name))
			}
			for _, deposit := range placement.deposits {
				if deposit.word != word {
					continue
				}
				part := source
				if placement.straddle {
					part = fmt.Sprintf("(%s & %s)", bigShiftRight(source, deposit.sourceShift), bigMask(deposit.bitCount))
				}
				w.line("%s |= %s;", variable, bigShiftLeft(part, deposit.destinationShift))
			}
		}
		w.line("writer.word(%s, %d, %t);", variable, wordBytes(group.size, word), littleEndian)
	}
}

// readStructure reads a struct's fields into target, an object made.
func (g *typeScriptGenerator) readStructure(w *sourceWriter, structure packedStruct, target string, depth int) {
	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			group := property.packed.(packedBitFieldGroup)
			values := g.readBits(w, group, property.littleEndian, target)
			for index, field := range group.fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				w.line("%s.%s = %s;", target, camelName(field.packedProperty.name), values[index])
			}
			continue
		}
		g.readInto(w, property.kind, property.packed, property.littleEndian, target+"."+camelName(property.name), depth)
	}
}

// readInto reads a value into place, an assignable expression.
func (g *typeScriptGenerator) readInto(w *sourceWriter, kind kind, packed any, littleEndian bool, place string, depth int) {
	switch kind {
	case kindStruct:
		structure := packed.(packedStruct)
		w.line("%s = {} as %s;", place, structure.name)
		g.readStructure(w, structure, place, depth)
		return
	case kindArray:
		array := packed.(packedArray)
		g.readList(w, fmt.Sprintf("%d", array.Length), array.ElementKind, array.Element, littleEndian, place, depth)
		return
	case kindSlice:
		slice := packed.(packedSlice)
		if byteElements(slice.ElementKind, slice.Element) {
			w.line("%s = reader.bytesOf(%d, %t);", place, slice.Length.size, littleEndian)
			if slice.maximum > 0 {
				w.line("if (%s.length > %d) throw new RangeError(`%s holds more than its maximum of %d items`);", place, slice.maximum, place, slice.maximum)
			}
			return
		}
		count := fmt.Sprintf("reader.length(%d, %t)", slice.Length.size, littleEndian)
		if slice.maximum > 0 {
			local := fmt.Sprintf("count%d", depth)
			w.open("{")
			w.line("const %s = %s;", local, count)
			w.line("if (%s > %d) throw new RangeError(`%s holds more than its maximum of %d items`);", local, slice.maximum, place, slice.maximum)
			g.readList(w, local, slice.ElementKind, slice.Element, littleEndian, place, depth)
			w.close("}")
			return
		}
		g.readList(w, count, slice.ElementKind, slice.Element, littleEndian, place, depth)
		return
	}
	w.line("%s = %s;", place, g.readValue(kind, packed, littleEndian, place))
}

func (g *typeScriptGenerator) readValue(kind kind, packed any, littleEndian bool, place string) string {
	switch kind {
	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, place, "TypeScript"); ok {
			return typeScriptCall("reader", primitive.method, endianArgument(primitive.size, littleEndian))
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		return fmt.Sprintf("reader.fixedText(%d)", length)
	case kindEnum:
		enum := packed.(packedEnum)
		primitive := kotlinIntegers[enum.reflection.Kind()]
		return fmt.Sprintf("enumName(%s, %s, %q)", enum.name, typeScriptCall("reader", primitive.method, endianArgument(primitive.size, littleEndian)), enum.name)
	case kindVariableString:
		variable := packed.(packedVariableString)
		return fmt.Sprintf("reader.%s(%d, %t)", typeScriptVariable(packed), variable.Length.size, littleEndian)
	}
	panic(fmt.Sprintf("%s uses a custom Go type, which has no TypeScript mapping", place))
}

// readList reads count elements into a new array at place, in order.
func (g *typeScriptGenerator) readList(w *sourceWriter, count string, kind kind, element any, littleEndian bool, place string, depth int) {
	item := itemName(depth)
	w.line("%s = [];", place)
	w.open("for (let %sIndex = 0, %sCount = %s; %sIndex < %sCount; %sIndex++) {", item, item, count, item, item, item)
	w.line("let %s: %s;", item, g.typeOf(kind, element, place))
	g.readInto(w, kind, element, littleEndian, item, depth+1)
	w.line("%s.push(%s);", place, item)
	w.close("}")
}

func (g *typeScriptGenerator) readBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, target string) []string {
	placements := group.placements(littleEndian)
	values := make([]string, len(group.fields))

	for word := 0; word < wordCount(group.size); word++ {
		if group.onlyTag() {
			// The decoder has read the tag already; this only moves past it.
			w.line("reader.word(%d, %t);", wordBytes(group.size, word), littleEndian)
			continue
		}
		w.line("const %s = reader.word(%d, %t);", wordVariable(target, group.groupIndex+word), wordBytes(group.size, word), littleEndian)
	}

	for _, placement := range placements {
		field := placement.field
		if field.bitFieldKind == bitFieldKindTag {
			continue
		}
		term := func(deposit bitDeposit) string {
			text := fmt.Sprintf("(%s & %s)", bigShiftRight(wordVariable(target, group.groupIndex+deposit.word), deposit.destinationShift), bigMask(deposit.bitCount))
			return bigShiftLeft(text, deposit.sourceShift)
		}
		raw := term(placement.deposits[0])
		if len(placement.deposits) == 2 {
			raw = fmt.Sprintf("(%s | %s)", raw, term(placement.deposits[1]))
		}
		switch field.bitFieldKind {
		case bitFieldKindBoolean:
			values[placement.index] = fmt.Sprintf("%s !== 0n", raw)
		case bitFieldKindEnum:
			values[placement.index] = fmt.Sprintf("enumName(%s, Number(%s), %q)", field.enum.name, raw, field.enum.name)
		case bitFieldKindInteger:
			primitive := kotlinIntegers[field.reflection.Kind()]
			value := raw
			if primitive.signed {
				value = fmt.Sprintf("BigInt.asIntN(%d, %s)", field.bitSize, raw)
			}
			if primitive.size < 8 {
				value = fmt.Sprintf("Number(%s)", value)
			}
			values[placement.index] = value
		default:
			panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no TypeScript mapping", field.packedProperty.name))
		}
	}
	return values
}
