var kotlinKeywords = map[string]bool{
	"as": true, "break": true, "class": true, "continue": true, "do": true, "else": true, "false": true,
	"for": true, "fun": true, "if": true, "in": true, "interface": true, "is": true, "null": true,
	"object": true, "package": true, "return": true, "super": true, "this": true, "throw": true,
	"true": true, "try": true, "typealias": true, "typeof": true, "val": true, "var": true, "when": true,
	"while": true,
}

// kotlinName turns a Go field name into a Kotlin property name.
func kotlinName(name string) string {
	result := camelName(name)

	if kotlinKeywords[result] {
		return "`" + result + "`"
	}

	return result
}

// camelName turns a Go name into lower camel case, treating a run of
// capitals as one word: ID becomes id, DeviceID deviceId, HTTPPort httpPort.
func camelName(name string) string {
	runes := []rune(name)
	words := []string{}
	start := 0

	for i := 1; i < len(runes); i++ {
		previous, current := runes[i-1], runes[i]
		nextIsLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])

		if unicode.IsUpper(current) && (unicode.IsLower(previous) || unicode.IsDigit(previous) || (unicode.IsUpper(previous) && nextIsLower)) {
			words = append(words, string(runes[start:i]))
			start = i
		}
	}
	words = append(words, string(runes[start:]))

	for i, word := range words {
		lower := strings.ToLower(word)
		if i == 0 {
			words[i] = lower
		} else {
			words[i] = strings.ToUpper(lower[:1]) + lower[1:]
		}
	}

	return strings.Join(words, "")
}

func capitalize(name string) string {
	name = strings.Trim(name, "`")
	return strings.ToUpper(name[:1]) + name[1:]
}

type sourceWriter struct {
	buffer *bytes.Buffer
	indent int
}

func (w *sourceWriter) line(format string, arguments ...any) {
	text := fmt.Sprintf(format, arguments...)
	if text == "" {
		w.buffer.WriteString("\n")
		return
	}
	w.buffer.WriteString(strings.Repeat("    ", w.indent))
	w.buffer.WriteString(text)
	w.buffer.WriteString("\n")
}

func (w *sourceWriter) open(format string, arguments ...any) {
	w.line(format, arguments...)
	w.indent++
}

func (w *sourceWriter) close(format string, arguments ...any) {
	w.indent--
	w.line(format, arguments...)
}

type kotlinGenerator struct {
	writerMethods map[string]bool
	readerMethods map[string]bool
	utf8Length    bool
}

// KotlinSource renders every registered enum, struct and message set as
// Kotlin with the same byte layout as the Go output: data classes with
// size(), toBytes() and fromBytes(), enum classes, and sealed interfaces
// with encode() and decode() for message sets.
func KotlinSource(packageName string) []byte {
	generator := &kotlinGenerator{writerMethods: map[string]bool{}, readerMethods: map[string]bool{}}

	body := &sourceWriter{buffer: &bytes.Buffer{}}

	for _, name := range sortedKeys(enums) {
		generator.enum(body, enums[name])
		body.line("")
	}

	for _, name := range sortedKeys(messageSets) {
		generator.messageSet(body, messageSets[name])
		body.line("")
	}

	for _, name := range sortedKeys(structs) {
		generator.structure(body, structs[name])
		body.line("")
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "// Code generated by github.com/0-Mqix/packed; DO NOT EDIT.\n\n")
	fmt.Fprintf(result, "package %s\n\n", packageName)
	result.Write(bytes.TrimRight(body.buffer.Bytes(), "\n"))
	result.WriteString("\n")

	helpers := &sourceWriter{buffer: result}
	generator.helpers(helpers)

	return bytes.TrimRight(result.Bytes(), "\n")
}

func (g *kotlinGenerator) enum(w *sourceWriter, enum packedEnum) {
	primitive := kotlinIntegers[enum.reflection.Kind()]

	w.open("enum class %s(val value: %s) {", enum.name, primitive.kotlinType)
	for index, value := range enum.values {
		literal := fmt.Sprintf("%d", index)
		if !primitive.signed {
			literal += "u"
		}
		w.line("%s(%s),", value, literal)
	}
	w.line(";")
	w.line("")
	w.open("companion object {")
	w.line("fun fromValue(value: %s): %s =", primitive.kotlinType, enum.name)
	w.line("    entries.firstOrNull { it.value == value } ?: throw IllegalArgumentException(\"unknown %s $value\")", enum.name)
	w.close("}")
	w.close("}")
}

func (g *kotlinGenerator) messageSet(w *sourceWriter, set packedMessageSet) {
	w.open("sealed interface %s {", set.name)
	w.line("// The message after prefix, which the caller fills (such as a routing byte).")
	w.line("fun encode(prefix: ByteArray = ByteArray(0)): ByteArray")
	w.line("")
	w.open("companion object {")
	w.line("// Decodes the message that starts at index and runs to the end of bytes.")
	w.open("fun decode(bytes: ByteArray, index: Int = 0): %s {", set.name)
	untagged := set.tagInBits && set.tagBits == 0
	tag := "$type"
	if untagged {
		tag = "0"
		w.line("val reader = PackedReader(bytes, index)")
		w.open("val message = try {")
		w.line("%s.read(reader)", set.variants[0].structure.name)
	} else {
		w.line("require(bytes.size > index) { \"empty %s message\" }", set.name)
		switch {
		case !set.tagInBits || set.tagBits == 8:
			w.line("val type = bytes[index].toInt() and 0xFF")
		case set.littleEndian:
			w.line("val type = bytes[index].toInt() and 0x%X", bitMask(set.tagBits))
		default:
			w.line("val type = (bytes[index].toInt() and 0xFF) ushr %d", 8-set.tagBits)
		}
		if set.tagInBits {
			w.line("val reader = PackedReader(bytes, index)")
		} else {
			w.line("val reader = PackedReader(bytes, index + 1)")
		}
		w.open("val message = try {")
		w.open("when (type) {")
		for _, variant := range set.variants {
			w.line("%d -> %s.read(reader)", variant.typeByte, variant.structure.name)
		}
		w.line("else -> throw IllegalArgumentException(\"unknown %s type $type\")", set.name)
		w.close("}")
	}
	w.indent--
	w.open("} catch (exception: IndexOutOfBoundsException) {")
	w.line("throw IllegalArgumentException(\"truncated %s type %s\", exception)", set.name, tag)
	w.close("}")
	w.line("require(reader.index == bytes.size) { \"%s type %s has ${bytes.size - reader.index} trailing bytes\" }", set.name, tag)
	w.line("return message")
	w.close("}")
	w.close("}")
	w.close("}")
}

// variantOf returns the message set a struct belongs to and its type byte.
func variantOf(structure packedStruct) (packedMessageSet, uint8, bool) {
	setName, ok := messageSetOfStruct[structure.name]
	if !ok {
		return packedMessageSet{}, 0, false
	}
	set := messageSets[setName]
	for _, variant := range set.variants {
		if variant.structure.name == structure.name {
			return set, variant.typeByte, true
		}
	}
	return packedMessageSet{}, 0, false
}

type kotlinField struct {
	name       string
	kotlinType string
}

func (g *kotlinGenerator) fields(structure packedStruct) []kotlinField {
	result := []kotlinField{}
	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			for _, field := range property.packed.(packedBitFieldGroup).fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				result = append(result, kotlinField{kotlinName(field.packedProperty.name), g.bitFieldType(field)})
			}
			continue
		}
		result = append(result, kotlinField{kotlinName(property.name), g.typeOf(property.kind, property.packed, structure.name+"."+property.name)})
	}
	return result
}

func (g *kotlinGenerator) bitFieldType(field packedBitField) string {
	switch field.bitFieldKind {
	case bitFieldKindBoolean:
		return "Boolean"
	case bitFieldKindInteger:
		return kotlinIntegers[field.reflection.Kind()].kotlinType
	case bitFieldKindEnum:
		return field.enum.name
	}
	panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no Kotlin mapping", field.packedProperty.name))
}

// converterPrimitive returns the primitive a built-in converter reads and
// writes, or false for StringConverter. language names the target in the
// panic for custom converters.
func converterPrimitive(converter any, location string, language string) (kotlinPrimitive, bool) {
	reflection := reflect.TypeOf(converter)
	if reflection.Kind() == reflect.Ptr {
		reflection = reflection.Elem()
	}
	if reflection == reflect.TypeFor[StringConverter]() {
		return kotlinPrimitive{}, false
	}
	primitive, ok := kotlinPrimitives[reflection]
	if !ok {
		panic(fmt.Sprintf("%s uses the custom converter %s, which has no %s mapping", location, reflection, language))
	}
	return primitive, true
}

func (g *kotlinGenerator) typeOf(kind kind, packed any, location string) string {
	switch kind {
	case kindStruct:
		return packed.(packedStruct).name
	case kindEnum:
		return packed.(packedEnum).name
	case kindVariableString:
		if packed.(packedVariableString).Bytes {
			return "ByteArray"
		}
		return "String"
	case kindConverter:
		if primitive, ok := converterPrimitive(packed, location, "Kotlin"); ok {
			return primitive.kotlinType
		}
		return "String"
	case kindConverterCast:
		if primitive, ok := converterPrimitive(packed.(converterCast).converter.instance, location, "Kotlin"); ok {
			return primitive.kotlinType
		}
		return "String"
	case kindArray:
		array := packed.(packedArray)
		return "List<" + g.typeOf(array.ElementKind, array.Element, location) + ">"
	case kindSlice:
		slice := packed.(packedSlice)
		return "List<" + g.typeOf(slice.ElementKind, slice.Element, location) + ">"
	}
	panic(fmt.Sprintf("%s uses a custom Go type, which has no Kotlin mapping", location))
}

func (g *kotlinGenerator) structure(w *sourceWriter, structure packedStruct) {
	set, typeByte, isVariant := variantOf(structure)

	fields := g.fields(structure)

	// A data class needs a property, so a struct without fields is a plain
	// class whose instances are all equal.
	if len(fields) == 0 {
		if isVariant {
			w.open("class %s : %s {", structure.name, set.name)
		} else {
			w.open("class %s {", structure.name)
		}
		w.line("override fun equals(other: Any?): Boolean = other is %s", structure.name)
		w.line("")
		w.line("override fun hashCode(): Int = 0")
		w.line("")
		w.line("override fun toString(): String = \"%s()\"", structure.name)
		w.line("")
	} else {
		w.open("data class %s(", structure.name)
		for _, field := range fields {
			w.line("val %s: %s,", field.name, field.kotlinType)
		}
		if isVariant {
			w.close(") : %s {", set.name)
		} else {
			w.close(") {")
		}
		w.indent++
	}

	if structure.dynamic {
		w.open("fun size(): Int {")
		w.line("var size = %d", structure.size)
		for _, property := range structure.properties {
			if property.dynamic {
				g.dynamicSize(w, property.kind, property.packed, kotlinName(property.name), 0)
			}
		}
		w.line("return size")
		w.close("}")
	} else {
		w.line("fun size(): Int = %d", structure.size)
	}
	w.line("")

	w.open("fun toBytes(bytes: ByteArray, index: Int): Int {")
	w.line("val writer = PackedWriter(bytes, index)")
	w.line("write(writer)")
	w.line("return writer.index")
	w.close("}")
	w.line("")

	if isVariant && set.tagInBits {
		w.open("override fun encode(prefix: ByteArray): ByteArray {")
		w.line("val bytes = prefix.copyOf(prefix.size + size())")
		w.line("toBytes(bytes, prefix.size)")
		w.line("return bytes")
		w.close("}")
		w.line("")
	} else if isVariant {
		w.open("override fun encode(prefix: ByteArray): ByteArray {")
		w.line("val bytes = prefix.copyOf(prefix.size + 1 + size())")
		if typeByte > 127 {
			w.line("bytes[prefix.size] = %d.toByte()", typeByte)
		} else {
			w.line("bytes[prefix.size] = %d", typeByte)
		}
		w.line("toBytes(bytes, prefix.size + 1)")
		w.line("return bytes")
		w.close("}")
		w.line("")
	}

	w.open("internal fun write(writer: PackedWriter) {")
	for _, property := range structure.properties {
		g.writeProperty(w, property, "", 0)
	}
	w.close("}")
	w.line("")

	w.open("companion object {")
	w.line("fun fromBytes(bytes: ByteArray, index: Int): %s = read(PackedReader(bytes, index))", structure.name)
	w.line("")
	w.open("internal fun read(reader: PackedReader): %s {", structure.name)
	construct := g.readStructure(w, structure, "", 0)
	w.line("return %s", construct)
	w.close("}")
	w.close("}")

	w.close("}")
}

func (g *kotlinGenerator) dynamicSize(w *sourceWriter, kind kind, packed any, value string, depth int) {
	switch kind {

	case kindVariableString:
		if packed.(packedVariableString).Bytes {
			w.line("size += %d + %s.size", packed.(packedVariableString).Length.size, value)
			break
		}
		g.utf8Length = true
		w.line("size += %d + utf8Length(%s)", packed.(packedVariableString).Length.size, value)

	case kindStruct:
		w.line("size += %s.size()", value)

	case kindSlice:
		slice := packed.(packedSlice)

		if !isDynamic(slice.ElementKind, slice.Element) {
			w.line("size += %d + %s.size * %d", slice.Length.size, value, slice.ElementSize)
			return
		}

		w.line("size += %d", slice.Length.size)
		item := itemName(depth)
		w.open("for (%s in %s) {", item, value)
		g.dynamicSize(w, slice.ElementKind, slice.Element, item, depth+1)
		w.close("}")

	case kindArray:
		array := packed.(packedArray)
		item := itemName(depth)
		w.open("for (%s in %s) {", item, value)
		g.dynamicSize(w, array.ElementKind, array.Element, item, depth+1)
		w.close("}")

	default:
		panic("invalid dynamic property kind")
	}
}

func itemName(depth int) string {
	if depth == 0 {
		return "item"
	}
	return fmt.Sprintf("item%d", depth)
}

func access(prefix, name string) string {
	if prefix == "" {
		return name
	}
	return prefix + "." + name
}

// primitiveMethod names the reader and writer method for a primitive, with
// the endianness appended for multi-byte values.
func primitiveMethod(primitive kotlinPrimitive, littleEndian bool) string {
	if primitive.size == 1 {
		return primitive.method
	}
	return primitive.method + endianName(littleEndian)
}

// variableOperation names the reader and writer methods of a variable
// string or byte run: textUint16LittleEndian, bytesUint32LittleEndian.
func variableOperation(packed any) string {
	if packed.(packedVariableString).Bytes {
		return "bytes"
	}
	return "text"
}

func lengthMethod(prefix lengthPrefix, operation string, littleEndian bool) string {
	primitive := kotlinIntegers[prefix.reflection.Kind()]
	method := operation + capitalize(primitive.method)
	if primitive.size > 1 {
		method += endianName(littleEndian)
	}
	return method
}

func (g *kotlinGenerator) writeProperty(w *sourceWriter, property packedProperty, prefix string, depth int) {
	if property.kind == kindBitFieldGroup {
		g.writeBits(w, property.packed.(packedBitFieldGroup), property.littleEndian, prefix, depth)
		return
	}
	g.writeValue(w, property.kind, property.packed, access(prefix, kotlinName(property.name)), property.littleEndian, depth)
}

func (g *kotlinGenerator) writeValue(w *sourceWriter, kind kind, packed any, value string, littleEndian bool, depth int) {
	switch kind {

	case kindStruct:
		for _, child := range packed.(packedStruct).properties {
			g.writeProperty(w, child, value, depth)
		}

	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, value, "Kotlin"); ok {
			method := primitiveMethod(primitive, littleEndian)
			g.writerMethods[method] = true
			w.line("writer.%s(%s)", method, value)
			return
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		g.writerMethods["fixedText"] = true
		w.line("writer.fixedText(%s, %d)", value, length)

	case kindEnum:
		enum := packed.(packedEnum)
		method := primitiveMethod(kotlinIntegers[enum.reflection.Kind()], littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s.value)", method, value)

	case kindVariableString:
		method := lengthMethod(packed.(packedVariableString).Length, variableOperation(packed), littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s)", method, value)

	case kindArray:
		array := packed.(packedArray)
		w.line("require(%s.size == %d) { \"%s must hold %d items, not ${%s.size}\" }", value, array.Length, value, array.Length, value)
		item := itemName(depth)
		w.open("for (%s in %s) {", item, value)
		g.writeValue(w, array.ElementKind, array.Element, item, littleEndian, depth+1)
		w.close("}")

	case kindSlice:
		slice := packed.(packedSlice)
		method := lengthMethod(slice.Length, "length", littleEndian)
		g.writerMethods[method] = true
		if slice.maximum > 0 {
			w.line("require(%s.size <= %d) { \"%s holds more than its maximum of %d items\" }", value, slice.maximum, value, slice.maximum)
		}
		w.line("writer.%s(%s.size)", method, value)
		item := itemName(depth)
		w.open("for (%s in %s) {", item, value)
		g.writeValue(w, slice.ElementKind, slice.Element, item, littleEndian, depth+1)
		w.close("}")

	default:
		panic(fmt.Sprintf("%s uses a custom Go type, which has no Kotlin mapping", value))
	}
}

func kotlinMask(bits int) string {
	if bits >= 64 {
		return "-1L"
	}
	return fmt.Sprintf("0x%XL", bitMask(bits))
}

func shiftLeft(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s shl %d)", expression, shift)
}

func shiftRight(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s ushr %d)", expression, shift)
}

func wordName(prefix string, word int) string {
	if prefix == "" {
		return fmt.Sprintf("bits%d", word)
	}
	return fmt.Sprintf("%sBits%d", strings.ReplaceAll(strings.ReplaceAll(prefix, "`", ""), ".", ""), word)
}

func (g *kotlinGenerator) writeBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, prefix string, depth int) {
	placements := group.placements(littleEndian)

	for word := 0; word < wordCount(group.size); word++ {
		variable := wordName(prefix, group.groupIndex+word)
		w.line("var %s = 0L", variable)

		for _, placement := range placements {
			field := placement.field
			value := access(prefix, kotlinName(field.packedProperty.name))

			var source string
			if field.bitFieldKind == bitFieldKindTag {
				source = fmt.Sprintf("%dL", field.tagValue)
			} else if field.bitFieldKind == bitFieldKindBoolean {
				source = fmt.Sprintf("(if (%s) 1L else 0L)", value)
			} else if field.bitFieldKind == bitFieldKindEnum {
				source = fmt.Sprintf("(%s.value.toLong() and %s)", value, kotlinMask(field.bitSize))
			} else {
				source = fmt.Sprintf("(%s.toLong() and %s)", value, kotlinMask(field.bitSize))
			}

			for _, deposit := range placement.deposits {
				if deposit.word != word {
					continue
				}
				part := source
				if placement.straddle {
					part = fmt.Sprintf("(%s and %s)", shiftRight(source, deposit.sourceShift), kotlinMask(deposit.bitCount))
				}
				w.line("%s = %s or %s", variable, variable, shiftLeft(part, deposit.destinationShift))
			}
		}

		method := "word" + endianName(littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s, %d)", method, variable, wordBytes(group.size, word))
	}
}

func (g *kotlinGenerator) readStructure(w *sourceWriter, structure packedStruct, prefix string, depth int) string {
	arguments := []string{}

	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			group := property.packed.(packedBitFieldGroup)
			values := g.readBits(w, group, property.littleEndian, prefix)
			for index, field := range group.fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				arguments = append(arguments, fmt.Sprintf("%s = %s", kotlinName(field.packedProperty.name), values[index]))
			}
			continue
		}

		name := kotlinName(property.name)
		local := name
		if prefix != "" {
			local = strings.Trim(prefix, "`") + capitalize(name)
		}
		expression := g.readValue(w, property.kind, property.packed, property.littleEndian, local, depth)
		w.line("val %s = %s", local, expression)
		arguments = append(arguments, fmt.Sprintf("%s = %s", name, local))
	}

	return callExpression(structure.name, arguments, w.indent)
}

// callExpression keeps a call on one line while it fits and otherwise puts
// one argument per line, the way Kotlin formatters do.
func callExpression(name string, arguments []string, indent int) string {
	single := fmt.Sprintf("%s(%s)", name, strings.Join(arguments, ", "))
	if len(single)+indent*4 <= 100 {
		return single
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "%s(\n", name)
	for _, argument := range arguments {
		fmt.Fprintf(result, "%s%s,\n", strings.Repeat("    ", indent+1), argument)
	}
	fmt.Fprintf(result, "%s)", strings.Repeat("    ", indent))
	return result.String()
}

func (g *kotlinGenerator) readValue(w *sourceWriter, kind kind, packed any, littleEndian bool, local string, depth int) string {
	switch kind {

	case kindStruct:
		return g.readStructure(w, packed.(packedStruct), local, depth)

	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, local, "Kotlin"); ok {
			method := primitiveMethod(primitive, littleEndian)
			g.readerMethods[method] = true
			return fmt.Sprintf("reader.%s()", method)
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		g.readerMethods["fixedText"] = true
		return fmt.Sprintf("reader.fixedText(%d)", length)

	case kindEnum:
		enum := packed.(packedEnum)
		method := primitiveMethod(kotlinIntegers[enum.reflection.Kind()], littleEndian)
		g.readerMethods[method] = true
		return fmt.Sprintf("%s.fromValue(reader.%s())", enum.name, method)

	case kindVariableString:
		method := lengthMethod(packed.(packedVariableString).Length, variableOperation(packed), littleEndian)
		g.readerMethods[method] = true
		return fmt.Sprintf("reader.%s()", method)

	case kindArray:
		array := packed.(packedArray)
		return g.readList(w, fmt.Sprintf("%d", array.Length), array.ElementKind, array.Element, littleEndian, local, depth)

	case kindSlice:
		slice := packed.(packedSlice)
		method := lengthMethod(slice.Length, "length", littleEndian)
		g.readerMethods[method] = true
		count := fmt.Sprintf("reader.%s()", method)
		if slice.maximum > 0 {
			count = fmt.Sprintf("reader.%s().also { require(it <= %d) { \"%s holds more than its maximum of %d items\" } }", method, slice.maximum, local, slice.maximum)
		}
		return g.readList(w, count, slice.ElementKind, slice.Element, littleEndian, local, depth)
	}

	panic(fmt.Sprintf("%s uses a custom Go type, which has no Kotlin mapping", local))
}

// readList reads the elements inside a List(size) { } initializer, which
// runs once per index in order, so the reads stay sequential.
func (g *kotlinGenerator) readList(w *sourceWriter, size string, kind kind, element any, littleEndian bool, local string, depth int) string {
	inner := &sourceWriter{buffer: &bytes.Buffer{}, indent: w.indent + 1}
	item := local + "Item"
	expression := g.readValue(inner, kind, element, littleEndian, item, depth+1)

	if inner.buffer.Len() == 0 {
		return fmt.Sprintf("List(%s) { %s }", size, expression)
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "List(%s) {\n", size)
	result.Write(inner.buffer.Bytes())
	fmt.Fprintf(result, "%s%s\n", strings.Repeat("    ", w.indent+1), expression)
	fmt.Fprintf(result, "%s}", strings.Repeat("    ", w.indent))
	return result.String()
}

func (g *kotlinGenerator) readBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, prefix string) []string {
	placements := group.placements(littleEndian)
	values := make([]string, len(group.fields))

	for word := 0; word < wordCount(group.size); word++ {
		method := "word" + endianName(littleEndian)
		g.readerMethods[method] = true
		if group.onlyTag() {
			// The decoder has read the tag already; this only moves past it.
			w.line("reader.%s(%d)", method, wordBytes(group.size, word))
			continue
		}
		w.line("val %s = reader.%s(%d)", wordName(prefix, group.groupIndex+word), method, wordBytes(group.size, word))
	}

	for _, placement := range placements {
		if placement.field.bitFieldKind == bitFieldKindTag {
			continue
		}

		term := func(deposit bitDeposit) string {
			text := fmt.Sprintf("(%s and %s)", shiftRight(wordName(prefix, group.groupIndex+deposit.word), deposit.destinationShift), kotlinMask(deposit.bitCount))
			return shiftLeft(text, deposit.sourceShift)
		}

		raw := term(placement.deposits[0])
		if len(placement.deposits) == 2 {
			raw = fmt.Sprintf("(%s or %s)", raw, term(placement.deposits[1]))
		}

		field := placement.field
		switch field.bitFieldKind {
		case bitFieldKindBoolean:
			values[placement.index] = fmt.Sprintf("%s != 0L", raw)
		case bitFieldKindEnum:
			primitive := kotlinIntegers[field.reflection.Kind()]
			values[placement.index] = fmt.Sprintf("%s.fromValue(%s.to%s())", field.enum.name, raw, primitive.kotlinType)
		case bitFieldKindInteger:
			primitive := kotlinIntegers[field.reflection.Kind()]
			if primitive.signed {
				sign := fmt.Sprintf("(1L shl %d)", field.bitSize-1)
				values[placement.index] = fmt.Sprintf("((%s xor %s) - %s).to%s()", raw, sign, sign, primitive.kotlinType)
			} else {
				values[placement.index] = fmt.Sprintf("%s.to%s()", raw, primitive.kotlinType)
			}
		default:
			panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no Kotlin mapping", field.packedProperty.name))
		}
	}

	return values
}

type kotlinHelper struct {
	signature string
	body      []string
}

func integerWriter(name, kotlinType string, size int, littleEndian bool) kotlinHelper {
	body := []string{}
	value := "value.toLong()"
	if kotlinType == "Long" || kotlinType == "Double" {
		value = "value"
	}
	if kotlinType == "Float" {
		value = "value.toRawBits().toLong()"
	}
	if kotlinType == "Double" {
		value = "value.toRawBits()"
	}
	if size == 1 {
		switch kotlinType {
		case "Boolean":
			return kotlinHelper{fmt.Sprintf("fun %s(value: Boolean)", name), []string{"bytes[index] = (if (value) 1 else 0).toByte()", "index += 1"}}
		case "Byte":
			return kotlinHelper{fmt.Sprintf("fun %s(value: Byte)", name), []string{"bytes[index] = value", "index += 1"}}
		}
		return kotlinHelper{fmt.Sprintf("fun %s(value: %s)", name, kotlinType), []string{"bytes[index] = value.toByte()", "index += 1"}}
	}
	body = append(body, fmt.Sprintf("word%s(%s, %d)", endianName(littleEndian), value, size))
	return kotlinHelper{fmt.Sprintf("fun %s(value: %s)", name, kotlinType), body}
}

func integerReader(name, kotlinType string, size int, littleEndian bool) kotlinHelper {
	if size == 1 {
		switch kotlinType {
		case "Boolean":
			return kotlinHelper{fmt.Sprintf("fun %s(): Boolean", name), []string{"return bytes[index++] != 0.toByte()"}}
		case "Byte":
			return kotlinHelper{fmt.Sprintf("fun %s(): Byte", name), []string{"return bytes[index++]"}}
		}
		return kotlinHelper{fmt.Sprintf("fun %s(): %s", name, kotlinType), []string{fmt.Sprintf("return bytes[index++].to%s()", kotlinType)}}
	}
	word := fmt.Sprintf("word%s(%d)", endianName(littleEndian), size)
	switch kotlinType {
	case "Float":
		return kotlinHelper{fmt.Sprintf("fun %s(): Float", name), []string{fmt.Sprintf("return Float.fromBits(%s.toInt())", word)}}
	case "Double":
		return kotlinHelper{fmt.Sprintf("fun %s(): Double", name), []string{fmt.Sprintf("return Double.fromBits(%s)", word)}}
	case "Long":
		return kotlinHelper{fmt.Sprintf("fun %s(): Long", name), []string{"return " + word}}
	}
	return kotlinHelper{fmt.Sprintf("fun %s(): %s", name, kotlinType), []string{fmt.Sprintf("return %s.to%s()", word, kotlinType)}}
}

func (g *kotlinGenerator) writerHelper(method string) kotlinHelper {
	switch method {
	case "wordLittleEndian":
		return kotlinHelper{"fun wordLittleEndian(value: Long, size: Int)", []string{
			"for (byte in 0 until size) {",
			"    bytes[index + byte] = (value ushr (8 * byte)).toByte()",
			"}",
			"index += size",
		}}
	case "wordBigEndian":
		return kotlinHelper{"fun wordBigEndian(value: Long, size: Int)", []string{
			"for (byte in 0 until size) {",
			"    bytes[index + size - 1 - byte] = (value ushr (8 * byte)).toByte()",
			"}",
			"index += size",
		}}
	case "fixedText":
		return kotlinHelper{"fun fixedText(value: String, length: Int)", []string{
			"val encoded = value.encodeToByteArray()",
			"val count = minOf(encoded.size, length)",
			"encoded.copyInto(bytes, index, 0, count)",
			"bytes.fill(0, index + count, index + length)",
			"index += length",
		}}
	}

	for _, operation := range []string{"length", "text", "bytes"} {
		if !strings.HasPrefix(method, operation) {
			continue
		}
		prefixType, littleEndian := splitEndian(strings.TrimPrefix(method, operation))
		primitive := integerByMethod(strings.ToLower(prefixType[:1]) + prefixType[1:])
		maximum := fmt.Sprintf("%d", bitMask(primitive.size*8))
		lengthWrite := g.lengthWrite(primitive, littleEndian)
		if operation == "length" {
			body := []string{}
			if primitive.size < 4 {
				body = append(body, fmt.Sprintf("require(length <= %s) { \"$length items do not fit a %s length prefix\" }", maximum, primitive.kotlinType))
			}
			body = append(body, lengthWrite...)
			return kotlinHelper{fmt.Sprintf("fun %s(length: Int)", method), body}
		}
		if operation == "bytes" {
			body := []string{"val length = value.size"}
			if primitive.size < 4 {
				body = append(body, fmt.Sprintf("require(length <= %s) { \"$length bytes do not fit a %s length prefix\" }", maximum, primitive.kotlinType))
			}
			body = append(body, lengthWrite...)
			body = append(body, "value.copyInto(bytes, index)", "index += length")
			return kotlinHelper{fmt.Sprintf("fun %s(value: ByteArray)", method), body}
		}
		body := []string{"val encoded = value.encodeToByteArray()", "val length = encoded.size"}
		if primitive.size < 4 {
			body = append(body, fmt.Sprintf("require(length <= %s) { \"$length bytes do not fit a %s length prefix\" }", maximum, primitive.kotlinType))
		}
		body = append(body, lengthWrite...)
		body = append(body, "encoded.copyInto(bytes, index)", "index += length")
		return kotlinHelper{fmt.Sprintf("fun %s(value: String)", method), body}
	}

	name, littleEndian := splitEndian(method)
	primitive := integerByMethod(name)
	if primitive.size > 1 {
		g.writerMethods["word"+endianName(littleEndian)] = true
	}
	return integerWriter(method, primitive.kotlinType, primitive.size, littleEndian)
}

func (g *kotlinGenerator) lengthWrite(primitive kotlinPrimitive, littleEndian bool) []string {
	if primitive.size == 1 {
		return []string{"bytes[index] = length.toByte()", "index += 1"}
	}
	g.writerMethods["word"+endianName(littleEndian)] = true
	return []string{fmt.Sprintf("word%s(length.toLong(), %d)", endianName(littleEndian), primitive.size)}
}

func (g *kotlinGenerator) readerHelper(method string) kotlinHelper {
	switch method {
	case "wordLittleEndian":
		return kotlinHelper{"fun wordLittleEndian(size: Int): Long", []string{
			"var value = 0L",
			"for (byte in 0 until size) {",
			"    value = value or ((bytes[index + byte].toLong() and 0xFF) shl (8 * byte))",
			"}",
			"index += size",
			"return value",
		}}
	case "wordBigEndian":
		return kotlinHelper{"fun wordBigEndian(size: Int): Long", []string{
			"var value = 0L",
			"for (byte in 0 until size) {",
			"    value = value or ((bytes[index + size - 1 - byte].toLong() and 0xFF) shl (8 * byte))",
			"}",
			"index += size",
			"return value",
		}}
	case "fixedText":
		return kotlinHelper{"fun fixedText(length: Int): String", []string{
			"var end = index + length",
			"while (end > index && bytes[end - 1] == 0.toByte()) end--",
			"val value = bytes.decodeToString(index, end)",
			"index += length",
			"return value",
		}}
	}

	for _, operation := range []string{"length", "text", "bytes"} {
		if !strings.HasPrefix(method, operation) {
			continue
		}
		prefixType, littleEndian := splitEndian(strings.TrimPrefix(method, operation))
		primitive := integerByMethod(strings.ToLower(prefixType[:1]) + prefixType[1:])
		var lengthRead string
		if primitive.size == 1 {
			lengthRead = "bytes[index++].toInt() and 0xFF"
		} else {
			g.readerMethods["word"+endianName(littleEndian)] = true
			lengthRead = fmt.Sprintf("word%s(%d).toInt()", endianName(littleEndian), primitive.size)
		}
		if operation == "length" {
			return kotlinHelper{fmt.Sprintf("fun %s(): Int", method), []string{"return " + lengthRead}}
		}
		if operation == "bytes" {
			return kotlinHelper{fmt.Sprintf("fun %s(): ByteArray", method), []string{
				"val length = " + lengthRead,
				"val value = bytes.copyOfRange(index, index + length)",
				"index += length",
				"return value",
			}}
		}
		return kotlinHelper{fmt.Sprintf("fun %s(): String", method), []string{
			"val length = " + lengthRead,
			"val value = bytes.decodeToString(index, index + length)",
			"index += length",
			"return value",
		}}
	}

	name, littleEndian := splitEndian(method)
	primitive := integerByMethod(name)
	if primitive.size > 1 {
		g.readerMethods["word"+endianName(littleEndian)] = true
	}
	return integerReader(method, primitive.kotlinType, primitive.size, littleEndian)
}

func splitEndian(method string) (string, bool) {
	if strings.HasSuffix(method, "LittleEndian") {
		return strings.TrimSuffix(method, "LittleEndian"), true
	}
	if strings.HasSuffix(method, "BigEndian") {
		return strings.TrimSuffix(method, "BigEndian"), false
	}
	return method, true
}

func integerByMethod(method string) kotlinPrimitive {
	for _, primitive := range kotlinPrimitives {
		if primitive.method == method {
			return primitive
		}
	}
	panic("unknown method " + method)
}

func (g *kotlinGenerator) helpers(w *sourceWriter) {
	writeClass := func(name string, constructor string, methods map[string]bool, helper func(string) kotlinHelper) {
		if len(methods) == 0 {
			return
		}

		collected := map[string]kotlinHelper{}
		for {
			added := false
			for method := range methods {
				if _, ok := collected[method]; !ok {
					collected[method] = helper(method)
					added = true
				}
			}
			if !added {
				break
			}
		}

		names := make([]string, 0, len(collected))
		for method := range collected {
			names = append(names, method)
		}
		sort.Strings(names)

		w.line("")
		w.open("internal class %s(%s) {", name, constructor)
		for index, method := range names {
			if index > 0 {
				w.line("")
			}
			helper := collected[method]
			w.open("%s {", helper.signature)
			for _, line := range helper.body {
				w.line("%s", line)
			}
			w.close("}")
		}
		w.close("}")
	}

	writeClass("PackedWriter", "private val bytes: ByteArray, var index: Int", g.writerMethods, g.writerHelper)
	writeClass("PackedReader", "private val bytes: ByteArray, var index: Int", g.readerMethods, g.readerHelper)

	if g.utf8Length {
		w.line("")
		w.open("private fun utf8Length(value: String): Int {")
		w.line("var length = 0")
		w.line("var index = 0")
		w.open("while (index < value.length) {")
		w.line("val character = value[index]")
		w.open("length += when {")
		w.line("character.code < 0x80 -> 1")
		w.line("character.code < 0x800 -> 2")
		w.line("character.isHighSurrogate() && index + 1 < value.length && value[index + 1].isLowSurrogate() -> {")
		w.line("    index++")
		w.line("    4")
		w.line("}")
		w.line("else -> 3")
		w.close("}")
		w.line("index++")
		w.close("}")
		w.line("return length")
		w.close("}")
	}
}
