package packed

import (
	"bytes"
	"fmt"
	"reflect"
	"sort"
	"strings"
)

// DynamicSource renders the dynamic layer of roots, the types of package
// packageName that embed Dynamic, as Go source: for each root its Schema
// constant, AppendPacked and Decode<Type>, and for every struct reachable
// from them an appendPacked<Function> and a decodePacked<Function>. The
// source is unformatted; package generate formats it. Like the DSL it is
// not safe for concurrent use.
//
// A struct's fields are laid out as the DSL lays out a struct: runs of
// Bools (and the presence bits of pointers) share bytes as bit runs, fixed
// fields are written by packed's converters at constant offsets, and each
// fixed stretch is bounds-checked once when read.
func DynamicSource(packageName string, imports []Import, roots []*Layout) []byte {
	// the converter variables are this file's own
	defer func(saved map[string]converterHash, identifiers map[string]string, last int, prefix string, savedImported map[string]bool) {
		converters, converterIdentifiers, converterLastIdentifier, converterPrefix, imported = saved, identifiers, last, prefix, savedImported
	}(converters, converterIdentifiers, converterLastIdentifier, converterPrefix, imported)
	converters, converterIdentifiers, converterLastIdentifier, converterPrefix, imported = map[string]converterHash{}, map[string]string{}, 0, "packedConverter", map[string]bool{}

	writer := &dynamicWriter{buffer: &bytes.Buffer{}}

	for _, root := range roots {
		writer.root(root)
	}

	visited := map[*Layout]bool{}
	for _, root := range roots {
		writer.helpers(root, visited)
	}

	source := &bytes.Buffer{}
	fmt.Fprintf(source, "// Code generated by github.com/0-Mqix/packed/dynamic; DO NOT EDIT.\n\n")
	fmt.Fprintf(source, "package %s\n\n", packageName)
	// the standard library's packages first, as goimports groups them
	standard := []Import{{Path: "encoding/binary"}, {Path: "unsafe"}}
	others := []Import{{Path: "github.com/0-Mqix/packed"}}
	for _, imported := range imports {
		if first, _, _ := strings.Cut(imported.Path, "/"); strings.Contains(first, ".") {
			others = append(others, imported)
		} else {
			standard = append(standard, imported)
		}
	}
	fmt.Fprintf(source, "import (\n")
	for _, group := range [][]Import{standard, others} {
		sort.Slice(group, func(a, b int) bool { return group[a].Path < group[b].Path })
		for _, imported := range group {
			if imported.Name != "" {
				fmt.Fprintf(source, "%s ", imported.Name)
			}
			fmt.Fprintf(source, "%q\n", imported.Path)
		}
		fmt.Fprintf(source, "\n")
	}
	fmt.Fprintf(source, ")\n\n")

	names := make([]string, 0, len(converterIdentifiers))
	hashes := map[string]string{}
	for hash, name := range converterIdentifiers {
		names = append(names, name)
		hashes[name] = hash
	}
	// in the order they were numbered
	sort.Slice(names, func(a, b int) bool {
		return len(names[a]) < len(names[b]) || len(names[a]) == len(names[b]) && names[a] < names[b]
	})

	if len(names) > 0 {
		fmt.Fprintf(source, "var (\n")
		for _, name := range names {
			fmt.Fprintf(source, "%s = &%s{}\n", name, converters[hashes[name]].reflection)
		}
		fmt.Fprintf(source, ")\n\n")
	}

	source.Write(writer.buffer.Bytes())
	return source.Bytes()
}

type dynamicWriter struct {
	buffer *bytes.Buffer
	// depth numbers the variables of nested loops and maps.
	depth int
	// presence numbers a function's presence variables.
	presence int
}

func (w *dynamicWriter) printf(format string, arguments ...any) {
	fmt.Fprintf(w.buffer, format, arguments...)
}

func (w *dynamicWriter) root(layout *Layout) {
	name := layout.Name

	w.printf("// %sSchema is the hash of %s's layout in packed's dynamic layer, the\n", name, name)
	w.printf("// first 8 bytes of each of its messages.\n")
	w.printf("const %sSchema uint64 = 0x%016x\n\n", name, layout.Schema())

	w.printf("// AppendPacked appends value's message to bytes: %sSchema, then value\n", name)
	w.printf("// in packed's dynamic layer. A value it can't hold, a time Unix\n")
	w.printf("// nanoseconds can't among them, is a *packed.EncodeError.\n")
	w.printf("func (value %s) AppendPacked(bytes []byte) (message []byte, err error) {\n", layout.Type)
	w.printf("defer packed.RecoverEncode(&err)\n")
	w.printf("bytes = packed.AppendSchema(bytes, %sSchema)\n", name)
	w.printf("return appendPacked%s(bytes, &value), nil\n", layout.Function)
	w.printf("}\n\n")

	w.printf("// Decode%s reads the message AppendPacked wrote. A message of another\n", name)
	w.printf("// version of %s is packed.ErrOutOfDate.\n", name)
	w.printf("func Decode%s(bytes []byte) (%s, error) {\n", name, layout.Type)
	w.printf("reader := packed.NewReader(bytes, %sSchema)\n", name)
	w.printf("var value %s\n", layout.Type)
	w.printf("decodePacked%s(reader, &value)\n", layout.Function)
	w.printf("if err := reader.Finish(); err != nil {\n")
	w.printf("return %s{}, err\n", layout.Type)
	w.printf("}\n")
	w.printf("return value, nil\n")
	w.printf("}\n\n")
}

// helpers writes the helpers of layout's structs, each once, in the order
// they are first reached.
func (w *dynamicWriter) helpers(layout *Layout, visited map[*Layout]bool) {
	if layout == nil || visited[layout] {
		return
	}
	visited[layout] = true

	if layout.Kind == LayoutStruct {
		w.depth, w.presence = 0, 0
		w.printf("func appendPacked%s(bytes []byte, value *%s) []byte {\n", layout.Function, layout.Type)
		w.appendStruct(layout, "value")
		w.printf("return bytes\n")
		w.printf("}\n\n")

		w.depth, w.presence = 0, 0
		w.printf("func decodePacked%s(reader *packed.Reader, value *%s) {\n", layout.Function, layout.Type)
		w.printf("if !reader.Enter() {\n")
		w.printf("return\n")
		w.printf("}\n")
		w.decodeStruct(layout, "value")
		w.printf("reader.Leave()\n")
		w.printf("}\n\n")

		for _, field := range layout.Fields {
			w.helpers(field.Layout, visited)
		}
		return
	}

	w.helpers(layout.Key, visited)
	w.helpers(layout.Element, visited)
}

// dynamicPart is a stretch of a struct's layout: fixed fields, the value of
// a pointer, or a field of variable length.
type dynamicPart struct {
	// segment holds fixed fields, laid out and written by packed's emitter.
	segment *packedStruct
	// variables are the presence variables the segment's bit runs read.
	variables []string
	// pointer is a pointer's value, after the run its presence bit is in.
	pointer *dynamicPointer
	field   *LayoutField
}

type dynamicPointer struct {
	field    LayoutField
	variable string
}

// parts lays a struct out: consecutive Bools and pointers form a bit run,
// each pointer's value follows its run, and consecutive fixed fields form
// one segment.
func (w *dynamicWriter) parts(layout *Layout) []dynamicPart {
	var (
		parts      []dynamicPart
		properties []packedProperty
		variables  []string
		run        []packedBitField
		pointers   []dynamicPointer
	)

	closeSegment := func() {
		if len(properties) > 0 {
			parts = append(parts, dynamicPart{segment: newSegment(properties), variables: variables})
		}
		properties, variables = nil, nil
	}

	closeRun := func() {
		if len(run) == 0 {
			return
		}
		properties = append(properties, createBitFieldGroup(run, true))
		run = nil
		if len(pointers) == 0 {
			return
		}
		closeSegment()
		for index := range pointers {
			parts = append(parts, dynamicPart{pointer: &pointers[index]})
		}
		pointers = nil
	}

	for _, field := range layout.Fields {
		switch {
		case field.Layout.Kind == LayoutBool:
			run = append(run, packedBitField{
				bitSize:        1,
				reflection:     reflect.TypeFor[bool](),
				bitFieldKind:   bitFieldKindBoolean,
				packedProperty: packedProperty{name: field.Name},
			})

		case field.Layout.Kind == LayoutPointer:
			variable := fmt.Sprintf("present%d", w.presence)
			w.presence++
			run = append(run, packedBitField{
				bitSize:          1,
				reflection:       reflect.TypeFor[bool](),
				bitFieldKind:     bitFieldKindPresence,
				packedProperty:   packedProperty{name: field.Name},
				presenceVariable: variable,
			})
			variables = append(variables, variable)
			pointers = append(pointers, dynamicPointer{field: field, variable: variable})

		case field.Layout.fixed():
			closeRun()
			kind, element, size := fixedElement(field.Layout)
			property := packedProperty{name: field.Name, kind: kind, packed: element, size: size, littleEndian: true, endianOverride: true}
			if kind == kindConverter {
				hash := registerConverter(element)
				property.converter = &hash
			}
			properties = append(properties, property)

		default:
			closeRun()
			closeSegment()
			parts = append(parts, dynamicPart{field: &field})
		}
	}

	closeRun()
	closeSegment()
	return parts
}

// newSegment is a struct of fixed properties, numbered and with its casts'
// variables as Struct does it.
func newSegment(properties []packedProperty) *packedStruct {
	segment := &packedStruct{properties: properties, littleEndian: true, converterCastRecievers: map[reflect.Type]int{}}
	for _, property := range properties {
		segment.size += property.size
		collectCasts(property.kind, property.packed, segment.converterCastRecievers)
	}
	groupIndex := 0
	segment.setBitFieldGroupIndexes(&groupIndex)
	return segment
}

func registerConverter(converter any) converterHash {
	hash := createConverterHash(converter)
	if _, exists := converters[hash.hash]; !exists {
		converters[hash.hash] = hash
	}
	return hash
}

// fixedElement is packed's model of a fixed layout: a converter, a cast to
// a named type or an int, or an array.
func fixedElement(layout *Layout) (kind, any, int) {
	if layout.Kind == LayoutArray {
		kind, element, size := fixedElement(layout.Element)
		array := packedArray{Length: layout.Length, Element: element, ElementKind: kind, ElementSize: size}
		return kindArray, array, layout.Length * size
	}

	converter, reciever := layout.converter()
	hash := registerConverter(converter)
	size := converter.(interface{ Size() int }).Size()

	if layout.Name == "" && layout.Kind != LayoutInt && layout.Kind != LayoutUint {
		return kindConverter, converter, size
	}

	cast := converterCast{converter: hash, reciever: reciever, size: size, targetName: layout.Type}
	if layout.Kind == LayoutInt || layout.Kind == LayoutUint {
		cast.overflow = "reader.Overflow()"
	}
	return kindConverterCast, cast, size
}

func collectCasts(kind kind, element any, recievers map[reflect.Type]int) {
	switch kind {
	case kindConverterCast:
		cast := element.(converterCast)
		if _, ok := recievers[cast.reciever]; !ok {
			recievers[cast.reciever] = len(recievers)
		}
	case kindArray:
		array := element.(packedArray)
		collectCasts(array.ElementKind, array.Element, recievers)
	}
}

func (w *dynamicWriter) declareCasts(recievers map[reflect.Type]int) {
	ordered := make([]reflect.Type, len(recievers))
	for reciever, index := range recievers {
		ordered[index] = reciever
	}
	for index, reciever := range ordered {
		w.printf("var r%d %s\n", index, reciever)
	}
}

// address is the pointer to expression.
func address(expression string) string {
	if strings.HasPrefix(expression, "(*") && strings.HasSuffix(expression, ")") {
		return expression[2 : len(expression)-1]
	}
	return "&" + expression
}

func (w *dynamicWriter) appendStruct(layout *Layout, value string) {
	for _, part := range w.parts(layout) {
		switch {
		case part.segment != nil:
			w.printf("{\n")
			w.printf("index := len(bytes)\n")
			w.printf("bytes = append(bytes, make([]byte, %d)...)\n", part.segment.size)
			w.declareCasts(part.segment.converterCastRecievers)
			offset := &position{}
			for _, property := range part.segment.properties {
				property.writeProperty(w.buffer, part.segment, "ToBytes", value, offset)
			}
			w.printf("}\n")

		case part.pointer != nil:
			field := value + "." + part.pointer.field.Name
			w.printf("if %s != nil {\n", field)
			w.appendValue(part.pointer.field.Layout.Element, "(*"+field+")")
			w.printf("}\n")

		default:
			w.appendValue(part.field.Layout, value+"."+part.field.Name)
		}
	}
}

func (w *dynamicWriter) appendValue(layout *Layout, expression string) {
	switch layout.Kind {
	case LayoutString:
		if layout.Name != "" {
			expression = "string(" + expression + ")"
		}
		w.printf("bytes = packed.AppendString(bytes, %s)\n", expression)

	case LayoutSlice:
		if layout.Element.Kind == LayoutUint8 && layout.Element.Name == "" {
			w.printf("bytes = packed.AppendBytes(bytes, %s)\n", expression)
			return
		}
		w.printf("bytes = packed.AppendCount(bytes, len(%s), %s == nil)\n", expression, expression)
		w.appendElements(layout.Element, expression)

	case LayoutArray:
		if layout.fixed() {
			w.appendFixed(layout, expression)
			return
		}
		w.appendElements(layout.Element, expression)

	case LayoutMap:
		entry := fmt.Sprintf("entry%d", w.depth)
		key := fmt.Sprintf("key%d", w.depth)
		element := fmt.Sprintf("element%d", w.depth)
		w.printf("bytes = packed.AppendCount(bytes, len(%s), %s == nil)\n", expression, expression)
		w.printf("for _, %s := range packed.SortedKeys(%s, func(bytes []byte, %s %s) []byte {\n", entry, expression, key, layout.Key.Type)
		w.depth++
		w.appendValue(layout.Key, key)
		w.printf("return bytes\n")
		w.printf("}) {\n")
		w.printf("bytes = append(bytes, %s.Bytes...)\n", entry)
		w.printf("%s := %s[%s.Key]\n", element, expression, entry)
		w.appendValue(layout.Element, element)
		w.depth--
		w.printf("}\n")

	case LayoutPointer:
		w.printf("if %s != nil {\n", expression)
		w.printf("bytes = append(bytes, 1)\n")
		w.appendValue(layout.Element, "(*"+expression+")")
		w.printf("} else {\n")
		w.printf("bytes = append(bytes, 0)\n")
		w.printf("}\n")

	case LayoutStruct:
		w.printf("bytes = appendPacked%s(bytes, %s)\n", layout.Function, address(expression))

	default:
		w.appendFixed(layout, expression)
	}
}

// appendElements writes the elements of a slice or an array: fixed ones
// with packed's emitter into bytes reserved for all of them at once.
func (w *dynamicWriter) appendElements(element *Layout, expression string) {
	index := fmt.Sprintf("i%d", w.depth)

	if element.fixed() {
		kind, model, size := fixedElement(element)
		segment := &packedStruct{converterCastRecievers: map[reflect.Type]int{}}
		collectCasts(kind, model, segment.converterCastRecievers)

		w.printf("{\n")
		w.printf("index := len(bytes)\n")
		w.printf("bytes = append(bytes, make([]byte, len(%s)*%d)...)\n", expression, size)
		w.declareCasts(segment.converterCastRecievers)
		w.printf("for %s := range %s {\n", index, expression)
		writeElement(w.buffer, segment, "ToBytes", kind, model, size, expression+"["+index+"]", true, "index", w.depth+1)
		w.printf("}\n")
		w.printf("}\n")
		return
	}

	w.printf("for %s := range %s {\n", index, expression)
	w.depth++
	w.appendValue(element, expression+"["+index+"]")
	w.depth--
	w.printf("}\n")
}

// appendFixed writes a fixed value that is no struct's field.
func (w *dynamicWriter) appendFixed(layout *Layout, expression string) {
	kind, model, size := fixedElement(layout)
	segment := &packedStruct{converterCastRecievers: map[reflect.Type]int{}}
	collectCasts(kind, model, segment.converterCastRecievers)

	w.printf("{\n")
	w.printf("index := len(bytes)\n")
	w.printf("bytes = append(bytes, make([]byte, %d)...)\n", size)
	w.declareCasts(segment.converterCastRecievers)
	w.fixedValue(segment, "ToBytes", kind, model, size, expression)
	w.printf("}\n")
}

// fixedValue writes or reads a fixed value at index: one converter call,
// or packed's loop for an array.
func (w *dynamicWriter) fixedValue(segment *packedStruct, functionName string, kind kind, model any, size int, expression string) {
	switch kind {
	case kindConverter:
		hash := createConverterHash(model)
		w.printf("%s.%sLittleEndian(%s, bytes, index)\n", getConverterName(hash.hash), functionName, address(expression))
	case kindConverterCast:
		model.(converterCast).Write(w.buffer, segment, expression, functionName, true, "index")
	default:
		writeElement(w.buffer, segment, functionName, kind, model, size, expression, true, "index", w.depth)
	}
}

func (w *dynamicWriter) decodeStruct(layout *Layout, value string) {
	for _, part := range w.parts(layout) {
		switch {
		case part.segment != nil:
			if len(part.variables) > 0 {
				w.printf("var %s bool\n", strings.Join(part.variables, ", "))
			}
			w.printf("if bytes, index, ok := reader.Take(%d); ok {\n", part.segment.size)
			w.declareCasts(part.segment.converterCastRecievers)
			offset := &position{}
			for _, property := range part.segment.properties {
				property.writeProperty(w.buffer, part.segment, "FromBytes", value, offset)
			}
			w.printf("}\n")

		case part.pointer != nil:
			field := value + "." + part.pointer.field.Name
			element := part.pointer.field.Layout.Element
			w.printf("if %s && reader.Allocate(unsafe.Sizeof(*%s)) {\n", part.pointer.variable, field)
			w.printf("%s = new(%s)\n", field, element.Type)
			w.decodeValue(element, "(*"+field+")")
			w.printf("}\n")

		default:
			w.decodeValue(part.field.Layout, value+"."+part.field.Name)
		}
	}
}

func (w *dynamicWriter) decodeValue(layout *Layout, expression string) {
	switch layout.Kind {
	case LayoutString:
		if layout.Name != "" {
			w.printf("%s = %s(reader.ReadString())\n", expression, layout.Type)
			return
		}
		w.printf("%s = reader.ReadString()\n", expression)

	case LayoutSlice:
		if layout.Element.Kind == LayoutUint8 && layout.Element.Name == "" {
			w.printf("%s = reader.Bytes()\n", expression)
			return
		}
		w.printf("if count, present := reader.Count(%d, unsafe.Sizeof(%s[0])); present {\n", layout.Element.MinimumSize(), expression)
		w.printf("%s = make(%s, count)\n", expression, layout.Type)
		w.decodeElements(layout.Element, expression)
		w.printf("}\n")

	case LayoutArray:
		if layout.fixed() {
			w.decodeFixed(layout, expression)
			return
		}
		w.decodeElements(layout.Element, expression)

	case LayoutMap:
		previous := fmt.Sprintf("previous%d", w.depth)
		key := fmt.Sprintf("key%d", w.depth)
		element := fmt.Sprintf("element%d", w.depth)
		minimum := layout.Key.MinimumSize() + layout.Element.MinimumSize()
		w.printf("if count, present := reader.Count(%d, unsafe.Sizeof(*new(%s))+unsafe.Sizeof(*new(%s))); present {\n", minimum, layout.Key.Type, layout.Element.Type)
		w.printf("%s = make(%s, count)\n", expression, layout.Type)
		w.printf("var %s []byte\n", previous)
		w.printf("for range count {\n")
		w.printf("start := reader.Position()\n")
		w.printf("var %s %s\n", key, layout.Key.Type)
		w.depth++
		w.decodeValue(layout.Key, key)
		w.printf("reader.Ascending(&%s, start)\n", previous)
		w.printf("var %s %s\n", element, layout.Element.Type)
		w.decodeValue(layout.Element, element)
		w.depth--
		w.printf("%s[%s] = %s\n", expression, key, element)
		w.printf("}\n")
		w.printf("reader.Unique(len(%s), count)\n", expression)
		w.printf("}\n")

	case LayoutPointer:
		w.printf("if reader.Present() && reader.Allocate(unsafe.Sizeof(*%s)) {\n", expression)
		w.printf("%s = new(%s)\n", expression, layout.Element.Type)
		w.decodeValue(layout.Element, "(*"+expression+")")
		w.printf("}\n")

	case LayoutStruct:
		w.printf("decodePacked%s(reader, %s)\n", layout.Function, address(expression))

	default:
		w.decodeFixed(layout, expression)
	}
}

// decodeElements reads the elements of a slice or an array: fixed ones
// with packed's emitter from bytes bounds-checked once for all of them.
func (w *dynamicWriter) decodeElements(element *Layout, expression string) {
	index := fmt.Sprintf("i%d", w.depth)

	if element.fixed() {
		kind, model, size := fixedElement(element)
		segment := &packedStruct{converterCastRecievers: map[reflect.Type]int{}}
		collectCasts(kind, model, segment.converterCastRecievers)

		w.printf("if bytes, index, ok := reader.Take(len(%s)*%d); ok {\n", expression, size)
		w.declareCasts(segment.converterCastRecievers)
		w.printf("for %s := range %s {\n", index, expression)
		writeElement(w.buffer, segment, "FromBytes", kind, model, size, expression+"["+index+"]", true, "index", w.depth+1)
		w.printf("}\n")
		w.printf("}\n")
		return
	}

	w.printf("for %s := range %s {\n", index, expression)
	w.depth++
	w.decodeValue(element, expression+"["+index+"]")
	w.depth--
	w.printf("}\n")
}

// decodeFixed reads a fixed value that is no struct's field.
func (w *dynamicWriter) decodeFixed(layout *Layout, expression string) {
	kind, model, size := fixedElement(layout)
	segment := &packedStruct{converterCastRecievers: map[reflect.Type]int{}}
	collectCasts(kind, model, segment.converterCastRecievers)

	w.printf("if bytes, index, ok := reader.Take(%d); ok {\n", size)
	w.declareCasts(segment.converterCastRecievers)
	w.fixedValue(segment, "FromBytes", kind, model, size, expression)
	w.printf("}\n")
}
