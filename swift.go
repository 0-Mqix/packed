var swiftKeywords = map[string]bool{
	"associatedtype": true, "as": true, "await": true, "break": true, "case": true, "catch": true,
	"class": true, "continue": true, "default": true, "defer": true, "deinit": true, "do": true,
	"else": true, "enum": true, "extension": true, "fallthrough": true, "false": true,
	"fileprivate": true, "for": true, "func": true, "guard": true, "if": true, "import": true,
	"in": true, "init": true, "inout": true, "internal": true, "is": true, "let": true, "nil": true,
	"open": true, "operator": true, "precedencegroup": true, "private": true, "protocol": true,
	"public": true, "repeat": true, "rethrows": true, "return": true, "self": true, "static": true,
	"struct": true, "subscript": true, "super": true, "switch": true, "throw": true, "throws": true,
	"true": true, "try": true, "typealias": true, "var": true, "where": true, "while": true,
}

// swiftIdentifier escapes a Swift keyword with backticks.
func swiftIdentifier(name string) string {
	if swiftKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

// swiftName turns a Go field name into a Swift property name.
func swiftName(name string) string {
	return swiftIdentifier(camelName(name))
}

// swiftLocal names the local variable a read stores a field in: the field
// name, prefixed with the path of the nested struct or list item it is in.
func swiftLocal(prefix, name string) string {
	if prefix == "" {
		return swiftName(name)
	}
	return swiftIdentifier(strings.Trim(prefix, "`") + capitalize(camelName(name)))
}

// swiftType maps a primitive to its Swift type through its method name:
// uint16 becomes UInt16, int8 Int8, float32 Float.
func swiftType(primitive kotlinPrimitive) string {
	switch primitive.method {
	case "boolean":
		return "Bool"
	case "float32":
		return "Float"
	case "float64":
		return "Double"
	}
	if strings.HasPrefix(primitive.method, "uint") {
		return "UInt" + strings.TrimPrefix(primitive.method, "uint")
	}
	return "Int" + strings.TrimPrefix(primitive.method, "int")
}

type swiftGenerator struct {
	writerMethods map[string]bool
	readerMethods map[string]bool
}

// SwiftSource renders every registered enum, struct and message set as
// Swift with the same byte layout as the Go output: structs with size(),
// toBytes() and fromBytes(), enums with their wire type as raw value, and
// enums with associated values with encode() and decode() for message sets.
// The output uses the standard library only and is clean in Swift 6
// language mode.
//
// Reads throw PackedError, which SwiftErrorSource declares once for every
// generated file: in the same module, or in a module the file imports
// (imports names the modules, one import line each).
func SwiftSource(imports ...string) []byte {
	generator := &swiftGenerator{writerMethods: map[string]bool{}, readerMethods: map[string]bool{}}

	body := &sourceWriter{buffer: &bytes.Buffer{}}
	for _, module := range imports {
		body.line("import %s", module)
	}
	if len(imports) > 0 {
		body.line("")
	}

	for _, name := range sortedKeys(enums) {
		generator.enum(body, enums[name])
		body.line("")
	}

	for _, name := range sortedKeys(messageSets) {
		generator.messageSet(body, messageSets[name])
		body.line("")
	}

	for _, name := range sortedKeys(structs) {
		generator.structure(body, structs[name])
		body.line("")
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "// Code generated by github.com/0-Mqix/packed; DO NOT EDIT.\n\n")
	result.Write(bytes.TrimRight(body.buffer.Bytes(), "\n"))
	result.WriteString("\n")

	helpers := &sourceWriter{buffer: result}
	generator.helpers(helpers)

	return bytes.TrimRight(result.Bytes(), "\n")
}

// SwiftErrorSource renders PackedError, the error every generated Swift file
// throws. It goes in one module, so that all generated files, in that
// module and in those importing it, throw and catch the same type.
func SwiftErrorSource() []byte {
	w := &sourceWriter{buffer: &bytes.Buffer{}}
	fmt.Fprintf(w.buffer, "// Code generated by github.com/0-Mqix/packed; DO NOT EDIT.\n\n")
	errorType(w)
	return bytes.TrimRight(w.buffer.Bytes(), "\n")
}

func errorType(w *sourceWriter) {
	w.line("/// What fromBytes, decode and the enum initializers throw.")
	w.open("public enum PackedError: Error, Equatable, Sendable {")
	w.line("/// The input ended before the value did.")
	w.line("case truncated")
	w.line("/// An enum field holds a value that has no case.")
	w.line("case unknownValue(enumeration: String, value: Int64)")
	w.line("/// A list holds more items than its maximum.")
	w.line("case overMaximum(field: String, count: Int)")
	w.line("/// A message set was decoded from no bytes.")
	w.line("case empty(set: String)")
	w.line("/// A message set's type byte has no variant.")
	w.line("case unknownType(set: String, type: UInt8)")
	w.line("/// A message set's input ended before the variant did.")
	w.line("case truncatedMessage(set: String, type: UInt8)")
	w.line("/// A message set's input continues after the variant.")
	w.line("case trailingBytes(set: String, type: UInt8, count: Int)")
	w.close("}")
}

func (g *swiftGenerator) enum(w *sourceWriter, enum packedEnum) {
	wire := swiftType(kotlinIntegers[enum.reflection.Kind()])

	w.open("public enum %s: %s, CaseIterable, Sendable {", enum.name, wire)
	for index, value := range enum.values {
		w.line("case %s = %d", swiftName(value), index)
	}
	w.line("")
	w.open("public init(validating rawValue: %s) throws {", wire)
	w.open("guard let value = %s(rawValue: rawValue) else {", enum.name)
	w.line("throw PackedError.unknownValue(enumeration: \"%s\", value: Int64(truncatingIfNeeded: rawValue))", enum.name)
	w.close("}")
	w.line("self = value")
	w.close("}")
	w.close("}")
}

func (g *swiftGenerator) messageSet(w *sourceWriter, set packedMessageSet) {
	w.open("public enum %s: Equatable, Sendable {", set.name)
	for _, variant := range set.variants {
		w.line("case %s(%s)", swiftName(variant.structure.name), variant.structure.name)
	}
	w.line("")

	w.line("/// The message after prefix, which the caller fills (such as a routing byte).")
	w.open("public func encode(prefix: [UInt8] = []) -> [UInt8] {")
	w.line("switch self {")
	for _, variant := range set.variants {
		w.line("case .%s(let message): return message.encode(prefix: prefix)", swiftName(variant.structure.name))
	}
	w.line("}")
	w.close("}")
	w.line("")

	w.line("/// Decodes the message that starts at index and runs to the end of bytes.")
	w.open("public static func decode(_ bytes: [UInt8], from index: Int = 0) throws -> %s {", set.name)
	untagged := set.tagInBits && set.tagBits == 0
	tag := "type"
	if untagged {
		tag = "0"
		w.line("var reader = PackedReader(bytes: bytes, index: index)")
		w.line("let message: %s", set.name)
		w.open("do {")
		w.line("message = try .%s(%s.read(&reader))", swiftName(set.variants[0].structure.name), set.variants[0].structure.name)
	} else {
		w.open("guard index < bytes.count else {")
		w.line("throw PackedError.empty(set: \"%s\")", set.name)
		w.close("}")
		switch {
		case !set.tagInBits || set.tagBits == 8:
			w.line("let type = bytes[index]")
		case set.littleEndian:
			w.line("let type = bytes[index] & 0x%X", bitMask(set.tagBits))
		default:
			w.line("let type = bytes[index] >> %d", 8-set.tagBits)
		}
		if set.tagInBits {
			w.line("var reader = PackedReader(bytes: bytes, index: index)")
		} else {
			w.line("var reader = PackedReader(bytes: bytes, index: index + 1)")
		}
		w.line("let message: %s", set.name)
		w.open("do {")
		w.line("switch type {")
		for _, variant := range set.variants {
			w.line("case %d: message = try .%s(%s.read(&reader))", variant.typeByte, swiftName(variant.structure.name), variant.structure.name)
		}
		w.line("default: throw PackedError.unknownType(set: \"%s\", type: type)", set.name)
		w.line("}")
	}
	w.indent--
	w.open("} catch PackedError.truncated {")
	w.line("throw PackedError.truncatedMessage(set: \"%s\", type: %s)", set.name, tag)
	w.close("}")
	w.open("guard reader.index == bytes.count else {")
	w.line("throw PackedError.trailingBytes(set: \"%s\", type: %s, count: bytes.count - reader.index)", set.name, tag)
	w.close("}")
	w.line("return message")
	w.close("}")
	w.close("}")
}

type swiftField struct {
	name      string
	swiftType string
}

func (g *swiftGenerator) fields(structure packedStruct) []swiftField {
	result := []swiftField{}
	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			for _, field := range property.packed.(packedBitFieldGroup).fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				result = append(result, swiftField{swiftName(field.packedProperty.name), g.bitFieldType(field)})
			}
			continue
		}
		result = append(result, swiftField{swiftName(property.name), g.typeOf(property.kind, property.packed, structure.name+"."+property.name)})
	}
	return result
}

func (g *swiftGenerator) bitFieldType(field packedBitField) string {
	switch field.bitFieldKind {
	case bitFieldKindBoolean:
		return "Bool"
	case bitFieldKindInteger:
		return swiftType(kotlinIntegers[field.reflection.Kind()])
	case bitFieldKindEnum:
		return field.enum.name
	}
	panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no Swift mapping", field.packedProperty.name))
}

func (g *swiftGenerator) typeOf(kind kind, packed any, location string) string {
	switch kind {
	case kindStruct:
		return packed.(packedStruct).name
	case kindEnum:
		return packed.(packedEnum).name
	case kindVariableString:
		if packed.(packedVariableString).Bytes {
			return "[UInt8]"
		}
		return "String"
	case kindConverter:
		if primitive, ok := converterPrimitive(packed, location, "Swift"); ok {
			return swiftType(primitive)
		}
		return "String"
	case kindConverterCast:
		if primitive, ok := converterPrimitive(packed.(converterCast).converter.instance, location, "Swift"); ok {
			return swiftType(primitive)
		}
		return "String"
	case kindArray:
		array := packed.(packedArray)
		return "[" + g.typeOf(array.ElementKind, array.Element, location) + "]"
	case kindSlice:
		slice := packed.(packedSlice)
		return "[" + g.typeOf(slice.ElementKind, slice.Element, location) + "]"
	}
	panic(fmt.Sprintf("%s uses a custom Go type, which has no Swift mapping", location))
}

func (g *swiftGenerator) structure(w *sourceWriter, structure packedStruct) {
	set, typeByte, isVariant := variantOf(structure)

	fields := g.fields(structure)

	w.open("public struct %s: Equatable, Sendable {", structure.name)
	for _, field := range fields {
		w.line("public var %s: %s", field.name, field.swiftType)
	}
	w.line("")

	parameters := make([]string, len(fields))
	for index, field := range fields {
		parameters[index] = field.name + ": " + field.swiftType
	}
	w.open("public %s {", swiftCall("init", parameters, w.indent))
	for _, field := range fields {
		w.line("self.%s = %s", field.name, field.name)
	}
	w.close("}")
	w.line("")

	if structure.dynamic {
		w.open("public func size() -> Int {")
		w.line("var size = %d", structure.size)
		for _, property := range structure.properties {
			if property.dynamic {
				g.dynamicSize(w, property.kind, property.packed, swiftName(property.name), 0)
			}
		}
		w.line("return size")
		w.close("}")
	} else {
		w.line("public func size() -> Int { %d }", structure.size)
	}
	w.line("")

	w.line("/// Writes the struct at index and returns the index just past it.")
	w.line("@discardableResult")
	w.open("public func toBytes(_ bytes: inout [UInt8], _ index: Int) -> Int {")
	w.line("PackedWriter.write(into: &bytes, at: index) { writer in self.write(&writer) }")
	w.close("}")
	w.line("")

	w.line("/// Reads the struct at index and returns it with the index just past it.")
	w.open("public static func fromBytes(_ bytes: [UInt8], _ index: Int) throws -> (value: %s, end: Int) {", structure.name)
	w.line("var reader = PackedReader(bytes: bytes, index: index)")
	w.line("let value = try read(&reader)")
	w.line("return (value, reader.index)")
	w.close("}")
	w.line("")

	if isVariant && set.tagInBits {
		w.line("/// The struct with its tag after prefix, as the message set sends it.")
		w.open("public func encode(prefix: [UInt8] = []) -> [UInt8] {")
		w.line("var bytes = prefix")
		w.line("bytes.append(contentsOf: repeatElement(0, count: size()))")
		w.line("toBytes(&bytes, prefix.count)")
		w.line("return bytes")
		w.close("}")
		w.line("")
	} else if isVariant {
		w.line("/// The type byte followed by the struct after prefix, as the message set sends it.")
		w.open("public func encode(prefix: [UInt8] = []) -> [UInt8] {")
		w.line("var bytes = prefix")
		w.line("bytes.append(contentsOf: repeatElement(0, count: 1 + size()))")
		w.line("bytes[prefix.count] = %d", typeByte)
		w.line("toBytes(&bytes, prefix.count + 1)")
		w.line("return bytes")
		w.close("}")
		w.line("")
	}

	w.open("fileprivate func write(_ writer: inout PackedWriter) {")
	for _, property := range structure.properties {
		g.writeProperty(w, property, "", 0)
	}
	w.close("}")
	w.line("")

	w.open("fileprivate static func read(_ reader: inout PackedReader) throws -> %s {", structure.name)
	construct := g.readStructure(w, structure, "", 0)
	w.line("return %s", construct)
	w.close("}")

	w.close("}")
}

// swiftCall keeps a call or declaration on one line while it fits and
// otherwise puts one argument per line, without the trailing comma Swift
// before 6.1 rejects.
func swiftCall(name string, arguments []string, indent int) string {
	single := fmt.Sprintf("%s(%s)", name, strings.Join(arguments, ", "))
	if len(single)+indent*4 <= 100 {
		return single
	}

	result := &bytes.Buffer{}
	fmt.Fprintf(result, "%s(\n", name)
	for index, argument := range arguments {
		separator := ","
		if index == len(arguments)-1 {
			separator = ""
		}
		fmt.Fprintf(result, "%s%s%s\n", strings.Repeat("    ", indent+1), argument, separator)
	}
	fmt.Fprintf(result, "%s)", strings.Repeat("    ", indent))
	return result.String()
}

func (g *swiftGenerator) dynamicSize(w *sourceWriter, kind kind, packed any, value string, depth int) {
	switch kind {

	case kindVariableString:
		if packed.(packedVariableString).Bytes {
			w.line("size += %d + %s.count", packed.(packedVariableString).Length.size, value)
			break
		}
		w.line("size += %d + %s.utf8.count", packed.(packedVariableString).Length.size, value)

	case kindStruct:
		w.line("size += %s.size()", value)

	case kindSlice:
		slice := packed.(packedSlice)

		if !isDynamic(slice.ElementKind, slice.Element) {
			w.line("size += %d + %s.count * %d", slice.Length.size, value, slice.ElementSize)
			return
		}

		w.line("size += %d", slice.Length.size)
		item := itemName(depth)
		w.open("for %s in %s {", item, value)
		g.dynamicSize(w, slice.ElementKind, slice.Element, item, depth+1)
		w.close("}")

	case kindArray:
		array := packed.(packedArray)
		item := itemName(depth)
		w.open("for %s in %s {", item, value)
		g.dynamicSize(w, array.ElementKind, array.Element, item, depth+1)
		w.close("}")

	default:
		panic("invalid dynamic property kind")
	}
}

func (g *swiftGenerator) writeProperty(w *sourceWriter, property packedProperty, prefix string, depth int) {
	if property.kind == kindBitFieldGroup {
		g.writeBits(w, property.packed.(packedBitFieldGroup), property.littleEndian, prefix)
		return
	}
	g.writeValue(w, property.kind, property.packed, access(prefix, swiftName(property.name)), property.littleEndian, depth)
}

func (g *swiftGenerator) writeValue(w *sourceWriter, kind kind, packed any, value string, littleEndian bool, depth int) {
	switch kind {

	case kindStruct:
		for _, child := range packed.(packedStruct).properties {
			g.writeProperty(w, child, value, depth)
		}

	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, value, "Swift"); ok {
			method := primitiveMethod(primitive, littleEndian)
			g.writerMethods[method] = true
			w.line("writer.%s(%s)", method, value)
			return
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		g.writerMethods["fixedText"] = true
		w.line("writer.fixedText(%s, %d)", value, length)

	case kindEnum:
		enum := packed.(packedEnum)
		method := primitiveMethod(kotlinIntegers[enum.reflection.Kind()], littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s.rawValue)", method, value)

	case kindVariableString:
		method := lengthMethod(packed.(packedVariableString).Length, variableOperation(packed), littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s)", method, value)

	case kindArray:
		array := packed.(packedArray)
		w.line("precondition(%s.count == %d, \"%s must hold %d items, not \\(%s.count)\")", value, array.Length, strings.ReplaceAll(value, "`", ""), array.Length, value)
		item := itemName(depth)
		w.open("for %s in %s {", item, value)
		g.writeValue(w, array.ElementKind, array.Element, item, littleEndian, depth+1)
		w.close("}")

	case kindSlice:
		slice := packed.(packedSlice)
		method := lengthMethod(slice.Length, "length", littleEndian)
		g.writerMethods[method] = true
		if slice.maximum > 0 {
			w.line("precondition(%s.count <= %d, \"%s holds more than its maximum of %d items\")", value, slice.maximum, strings.ReplaceAll(value, "`", ""), slice.maximum)
		}
		w.line("writer.%s(%s.count)", method, value)
		item := itemName(depth)
		w.open("for %s in %s {", item, value)
		g.writeValue(w, slice.ElementKind, slice.Element, item, littleEndian, depth+1)
		w.close("}")

	default:
		panic(fmt.Sprintf("%s uses a custom Go type, which has no Swift mapping", value))
	}
}

func swiftMask(bits int) string {
	return fmt.Sprintf("0x%X", bitMask(bits))
}

func swiftShiftLeft(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s << %d)", expression, shift)
}

func swiftShiftRight(expression string, shift int) string {
	if shift == 0 {
		return expression
	}
	return fmt.Sprintf("(%s >> %d)", expression, shift)
}

// writeBits assembles each 64-bit word of a bit run in a UInt64 the way
// writeBits in kotlin.go does, then writes the word's bytes.
func (g *swiftGenerator) writeBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, prefix string) {
	placements := group.placements(littleEndian)

	for word := 0; word < wordCount(group.size); word++ {
		variable := wordName(prefix, group.groupIndex+word)
		w.line("var %s: UInt64 = 0", variable)

		for _, placement := range placements {
			field := placement.field
			value := access(prefix, swiftName(field.packedProperty.name))

			var source string
			if field.bitFieldKind == bitFieldKindTag {
				source = fmt.Sprintf("%d", field.tagValue)
			} else if field.bitFieldKind == bitFieldKindBoolean {
				source = fmt.Sprintf("UInt64(%s ? 1 : 0)", value)
			} else if field.bitFieldKind == bitFieldKindEnum {
				source = fmt.Sprintf("(UInt64(truncatingIfNeeded: %s.rawValue) & %s)", value, swiftMask(field.bitSize))
			} else {
				source = fmt.Sprintf("(UInt64(truncatingIfNeeded: %s) & %s)", value, swiftMask(field.bitSize))
			}

			for _, deposit := range placement.deposits {
				if deposit.word != word {
					continue
				}
				part := source
				if placement.straddle {
					part = fmt.Sprintf("(%s & %s)", swiftShiftRight(source, deposit.sourceShift), swiftMask(deposit.bitCount))
				}
				w.line("%s |= %s", variable, swiftShiftLeft(part, deposit.destinationShift))
			}
		}

		method := "word" + endianName(littleEndian)
		g.writerMethods[method] = true
		w.line("writer.%s(%s, %d)", method, variable, wordBytes(group.size, word))
	}
}

// readStructure reads every field into a local and returns the initializer
// call. Argument labels stay unescaped: a call needs no backticks around a
// keyword label, and Swift warns about them.
func (g *swiftGenerator) readStructure(w *sourceWriter, structure packedStruct, prefix string, depth int) string {
	arguments := []string{}

	for _, property := range structure.properties {
		if property.kind == kindBitFieldGroup {
			group := property.packed.(packedBitFieldGroup)
			values := g.readBits(w, group, property.littleEndian, prefix)
			for index, field := range group.fields {
				if field.bitFieldKind == bitFieldKindTag {
					continue
				}
				local := swiftLocal(prefix, field.packedProperty.name)
				w.line("let %s = %s", local, values[index])
				arguments = append(arguments, fmt.Sprintf("%s: %s", camelName(field.packedProperty.name), local))
			}
			continue
		}

		local := swiftLocal(prefix, property.name)
		expression := g.readValue(w, property.kind, property.packed, property.littleEndian, local, depth)
		if expression != local {
			w.line("let %s = %s", local, expression)
		}
		arguments = append(arguments, fmt.Sprintf("%s: %s", camelName(property.name), local))
	}

	return swiftCall(structure.name, arguments, w.indent)
}

// readValue returns the expression for one value. Lists are read with a
// loop into a local named local, which it returns.
func (g *swiftGenerator) readValue(w *sourceWriter, kind kind, packed any, littleEndian bool, local string, depth int) string {
	switch kind {

	case kindStruct:
		return g.readStructure(w, packed.(packedStruct), local, depth)

	case kindConverter, kindConverterCast:
		converter := packed
		if kind == kindConverterCast {
			converter = packed.(converterCast).converter.instance
		}
		if primitive, ok := converterPrimitive(converter, local, "Swift"); ok {
			method := primitiveMethod(primitive, littleEndian)
			g.readerMethods[method] = true
			return fmt.Sprintf("try reader.%s()", method)
		}
		length := reflect.ValueOf(converter).Elem().Interface().(StringConverter).Length
		g.readerMethods["fixedText"] = true
		return fmt.Sprintf("try reader.fixedText(%d)", length)

	case kindEnum:
		enum := packed.(packedEnum)
		method := primitiveMethod(kotlinIntegers[enum.reflection.Kind()], littleEndian)
		g.readerMethods[method] = true
		return fmt.Sprintf("try %s(validating: reader.%s())", enum.name, method)

	case kindVariableString:
		method := lengthMethod(packed.(packedVariableString).Length, variableOperation(packed), littleEndian)
		g.readerMethods[method] = true
		return fmt.Sprintf("try reader.%s()", method)

	case kindArray:
		array := packed.(packedArray)
		return g.readList(w, fmt.Sprintf("%d", array.Length), array.ElementKind, array.Element, littleEndian, local, depth)

	case kindSlice:
		slice := packed.(packedSlice)
		method := lengthMethod(slice.Length, "length", littleEndian)
		g.readerMethods[method] = true
		count := swiftIdentifier(strings.Trim(local, "`") + "Count")
		w.line("let %s = try reader.%s()", count, method)
		if slice.maximum > 0 {
			w.open("guard %s <= %d else {", count, slice.maximum)
			w.line("throw PackedError.overMaximum(field: \"%s\", count: %s)", strings.Trim(local, "`"), count)
			w.close("}")
		}
		return g.readList(w, count, slice.ElementKind, slice.Element, littleEndian, local, depth)
	}

	panic(fmt.Sprintf("%s uses a custom Go type, which has no Swift mapping", local))
}

// readList reads count elements in order into a new array named local.
func (g *swiftGenerator) readList(w *sourceWriter, count string, kind kind, element any, littleEndian bool, local string, depth int) string {
	w.line("var %s: [%s] = []", local, g.typeOf(kind, element, local))
	w.open("for _ in 0..<%s {", count)
	item := swiftIdentifier(strings.Trim(local, "`") + "Item")
	expression := g.readValue(w, kind, element, littleEndian, item, depth+1)
	w.line("%s.append(%s)", local, expression)
	w.close("}")
	return local
}

func (g *swiftGenerator) readBits(w *sourceWriter, group packedBitFieldGroup, littleEndian bool, prefix string) []string {
	placements := group.placements(littleEndian)
	values := make([]string, len(group.fields))

	for word := 0; word < wordCount(group.size); word++ {
		method := "word" + endianName(littleEndian)
		g.readerMethods[method] = true
		if group.onlyTag() {
			// The decoder has read the tag already; this only moves past it.
			w.line("_ = try reader.%s(%d)", method, wordBytes(group.size, word))
			continue
		}
		w.line("let %s = try reader.%s(%d)", wordName(prefix, group.groupIndex+word), method, wordBytes(group.size, word))
	}

	for _, placement := range placements {
		if placement.field.bitFieldKind == bitFieldKindTag {
			continue
		}

		term := func(deposit bitDeposit) string {
			text := fmt.Sprintf("(%s & %s)", swiftShiftRight(wordName(prefix, group.groupIndex+deposit.word), deposit.destinationShift), swiftMask(deposit.bitCount))
			return swiftShiftLeft(text, deposit.sourceShift)
		}

		raw := term(placement.deposits[0])
		if len(placement.deposits) == 2 {
			raw = fmt.Sprintf("(%s | %s)", raw, term(placement.deposits[1]))
		}

		field := placement.field
		switch field.bitFieldKind {
		case bitFieldKindBoolean:
			values[placement.index] = fmt.Sprintf("%s != 0", raw)
		case bitFieldKindEnum:
			wire := swiftType(kotlinIntegers[field.reflection.Kind()])
			values[placement.index] = fmt.Sprintf("try %s(validating: %s(truncatingIfNeeded: %s))", field.enum.name, wire, raw)
		case bitFieldKindInteger:
			primitive := kotlinIntegers[field.reflection.Kind()]
			if primitive.signed {
				sign := fmt.Sprintf("0x%X", uint64(1)<<(field.bitSize-1))
				values[placement.index] = fmt.Sprintf("%s(truncatingIfNeeded: (%s ^ %s) &- %s)", swiftType(primitive), raw, sign, sign)
			} else {
				values[placement.index] = fmt.Sprintf("%s(truncatingIfNeeded: %s)", swiftType(primitive), raw)
			}
		default:
			panic(fmt.Sprintf("bit field %s uses a custom Go type, which has no Swift mapping", field.packedProperty.name))
		}
	}

	return values
}

func (g *swiftGenerator) writerHelper(method string) kotlinHelper {
	switch method {
	case "wordLittleEndian":
		return kotlinHelper{"mutating func wordLittleEndian(_ value: UInt64, _ size: Int)", []string{
			"for byte in 0..<size {",
			"    bytes[index + byte] = UInt8(truncatingIfNeeded: value >> (8 * byte))",
			"}",
			"index += size",
		}}
	case "wordBigEndian":
		return kotlinHelper{"mutating func wordBigEndian(_ value: UInt64, _ size: Int)", []string{
			"for byte in 0..<size {",
			"    bytes[index + size - 1 - byte] = UInt8(truncatingIfNeeded: value >> (8 * byte))",
			"}",
			"index += size",
		}}
	case "fixedText":
		return kotlinHelper{"mutating func fixedText(_ value: String, _ length: Int)", []string{
			"var count = 0",
			"for byte in value.utf8.prefix(length) {",
			"    bytes[index + count] = byte",
			"    count += 1",
			"}",
			"for offset in count..<length {",
			"    bytes[index + offset] = 0",
			"}",
			"index += length",
		}}
	}

	for _, operation := range []string{"length", "text", "bytes"} {
		if !strings.HasPrefix(method, operation) {
			continue
		}
		prefixType, littleEndian := splitEndian(strings.TrimPrefix(method, operation))
		primitive := integerByMethod(strings.ToLower(prefixType[:1]) + prefixType[1:])
		lengthWrite := g.lengthWrite(primitive, littleEndian)

		// The UInt32 bound goes through UInt64 so the literal also
		// compiles where Int has 32 bits.
		check := func(unit string) []string {
			if primitive.size >= 8 {
				return nil
			}
			length := "length"
			if primitive.size == 4 {
				length = "UInt64(length)"
			}
			return []string{fmt.Sprintf("precondition(%s <= %d, \"\\(length) %s do not fit a %s length prefix\")", length, bitMask(primitive.size*8), unit, swiftType(primitive))}
		}

		if operation == "length" {
			body := append(check("items"), lengthWrite...)
			return kotlinHelper{fmt.Sprintf("mutating func %s(_ length: Int)", method), body}
		}
		if operation == "bytes" {
			body := []string{"let length = value.count"}
			body = append(body, check("bytes")...)
			body = append(body, lengthWrite...)
			body = append(body,
				"bytes.replaceSubrange(index..<index + length, with: value)",
				"index += length",
			)
			return kotlinHelper{fmt.Sprintf("mutating func %s(_ value: [UInt8])", method), body}
		}
		body := []string{"let length = value.utf8.count"}
		body = append(body, check("bytes")...)
		body = append(body, lengthWrite...)
		body = append(body,
			"for byte in value.utf8 {",
			"    bytes[index] = byte",
			"    index += 1",
			"}",
		)
		return kotlinHelper{fmt.Sprintf("mutating func %s(_ value: String)", method), body}
	}

	name, littleEndian := splitEndian(method)
	primitive := integerByMethod(name)
	signature := fmt.Sprintf("mutating func %s(_ value: %s)", method, swiftType(primitive))

	switch primitive.method {
	case "boolean":
		return kotlinHelper{signature, []string{"bytes[index] = value ? 1 : 0", "index += 1"}}
	case "uint8":
		return kotlinHelper{signature, []string{"bytes[index] = value", "index += 1"}}
	case "int8":
		return kotlinHelper{signature, []string{"bytes[index] = UInt8(bitPattern: value)", "index += 1"}}
	}

	g.writerMethods["word"+endianName(littleEndian)] = true
	value := "UInt64(truncatingIfNeeded: value)"
	if primitive.method == "float32" || primitive.method == "float64" {
		value = "UInt64(value.bitPattern)"
	}
	return kotlinHelper{signature, []string{fmt.Sprintf("word%s(%s, %d)", endianName(littleEndian), value, primitive.size)}}
}

func (g *swiftGenerator) lengthWrite(primitive kotlinPrimitive, littleEndian bool) []string {
	if primitive.size == 1 {
		return []string{"bytes[index] = UInt8(length)", "index += 1"}
	}
	g.writerMethods["word"+endianName(littleEndian)] = true
	return []string{fmt.Sprintf("word%s(UInt64(length), %d)", endianName(littleEndian), primitive.size)}
}

func (g *swiftGenerator) readerHelper(method string) kotlinHelper {
	switch method {
	case "advance":
		return kotlinHelper{"mutating func advance(_ size: Int) throws -> Int", []string{
			"guard index >= 0, size <= bytes.count - index else {",
			"    throw PackedError.truncated",
			"}",
			"let start = index",
			"index += size",
			"return start",
		}}
	case "wordLittleEndian":
		return kotlinHelper{"mutating func wordLittleEndian(_ size: Int) throws -> UInt64", []string{
			"let start = try advance(size)",
			"var value: UInt64 = 0",
			"for byte in 0..<size {",
			"    value |= UInt64(bytes[start + byte]) << (8 * byte)",
			"}",
			"return value",
		}}
	case "wordBigEndian":
		return kotlinHelper{"mutating func wordBigEndian(_ size: Int) throws -> UInt64", []string{
			"let start = try advance(size)",
			"var value: UInt64 = 0",
			"for byte in 0..<size {",
			"    value |= UInt64(bytes[start + size - 1 - byte]) << (8 * byte)",
			"}",
			"return value",
		}}
	case "fixedText":
		return kotlinHelper{"mutating func fixedText(_ length: Int) throws -> String", []string{
			"let start = try advance(length)",
			"var end = start + length",
			"while end > start && bytes[end - 1] == 0 {",
			"    end -= 1",
			"}",
			"return String(decoding: bytes[start..<end], as: UTF8.self)",
		}}
	}

	for _, operation := range []string{"length", "text", "bytes"} {
		if !strings.HasPrefix(method, operation) {
			continue
		}
		suffix := strings.TrimPrefix(method, operation)
		prefixType, littleEndian := splitEndian(suffix)
		primitive := integerByMethod(strings.ToLower(prefixType[:1]) + prefixType[1:])

		if operation == "bytes" {
			g.readerMethods["length"+suffix] = true
			return kotlinHelper{fmt.Sprintf("mutating func %s() throws -> [UInt8]", method), []string{
				fmt.Sprintf("let length = try length%s()", suffix),
				"let start = try advance(length)",
				"return Array(bytes[start..<start + length])",
			}}
		}
		if operation == "text" {
			g.readerMethods["length"+suffix] = true
			return kotlinHelper{fmt.Sprintf("mutating func %s() throws -> String", method), []string{
				fmt.Sprintf("let length = try length%s()", suffix),
				"let start = try advance(length)",
				"return String(decoding: bytes[start..<start + length], as: UTF8.self)",
			}}
		}

		signature := fmt.Sprintf("mutating func %s() throws -> Int", method)
		if primitive.size == 1 {
			return kotlinHelper{signature, []string{"return try Int(bytes[advance(1)])"}}
		}
		g.readerMethods["word"+endianName(littleEndian)] = true
		word := fmt.Sprintf("word%s(%d)", endianName(littleEndian), primitive.size)
		if primitive.size < 4 {
			return kotlinHelper{signature, []string{"return try Int(" + word + ")"}}
		}
		// A length Int cannot hold is longer than any input, so it is
		// reported as truncated rather than trapping.
		return kotlinHelper{signature, []string{
			"guard let length = Int(exactly: try " + word + ") else {",
			"    throw PackedError.truncated",
			"}",
			"return length",
		}}
	}

	name, littleEndian := splitEndian(method)
	primitive := integerByMethod(name)
	signature := fmt.Sprintf("mutating func %s() throws -> %s", method, swiftType(primitive))

	switch primitive.method {
	case "boolean":
		return kotlinHelper{signature, []string{"return try bytes[advance(1)] != 0"}}
	case "uint8":
		return kotlinHelper{signature, []string{"return try bytes[advance(1)]"}}
	case "int8":
		return kotlinHelper{signature, []string{"return try Int8(bitPattern: bytes[advance(1)])"}}
	}

	g.readerMethods["word"+endianName(littleEndian)] = true
	word := fmt.Sprintf("word%s(%d)", endianName(littleEndian), primitive.size)
	switch primitive.method {
	case "float32":
		return kotlinHelper{signature, []string{"return try Float(bitPattern: UInt32(truncatingIfNeeded: " + word + "))"}}
	case "float64":
		return kotlinHelper{signature, []string{"return try Double(bitPattern: " + word + ")"}}
	}
	return kotlinHelper{signature, []string{fmt.Sprintf("return try %s(truncatingIfNeeded: %s)", swiftType(primitive), word)}}
}

// helpers emits PackedWriter and PackedReader with only the methods the file
// uses. Both are fileprivate, so several generated files can share a module.
func (g *swiftGenerator) helpers(w *sourceWriter) {
	writeType := func(header []string, methods map[string]bool, helper func(string) kotlinHelper) {
		collected := map[string]kotlinHelper{}
		for {
			added := false
			for method := range methods {
				if _, ok := collected[method]; !ok {
					collected[method] = helper(method)
					added = true
				}
			}
			if !added {
				break
			}
		}

		names := make([]string, 0, len(collected))
		for method := range collected {
			names = append(names, method)
		}
		sort.Strings(names)

		w.line("")
		w.open("%s", header[0])
		for _, line := range header[1:] {
			w.line("%s", line)
		}
		for _, method := range names {
			w.line("")
			helper := collected[method]
			w.open("%s {", helper.signature)
			for _, line := range helper.body {
				w.line("%s", line)
			}
			w.close("}")
		}
		w.close("}")
	}

	writeType([]string{
		"fileprivate struct PackedWriter {",
		"var bytes: [UInt8] = []",
		"var index: Int",
		"",
		"/// Runs body on a writer that owns bytes for the duration, so writes",
		"/// do not copy the array.",
		"static func write(into bytes: inout [UInt8], at index: Int, _ body: (inout PackedWriter) -> Void) -> Int {",
		"    var writer = PackedWriter(index: index)",
		"    swap(&bytes, &writer.bytes)",
		"    body(&writer)",
		"    swap(&bytes, &writer.bytes)",
		"    return writer.index",
		"}",
	}, g.writerMethods, g.writerHelper)

	g.readerMethods["advance"] = true
	writeType([]string{
		"fileprivate struct PackedReader {",
		"let bytes: [UInt8]",
		"var index: Int",
	}, g.readerMethods, g.readerHelper)
}
